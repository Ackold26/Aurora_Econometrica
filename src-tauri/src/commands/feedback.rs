//! Здесь остаются: реэкспорт `form_category`/`CATEGORY_MAP` (сторож `guard_cpd88_feedback_category_map.rs`
//! линкуется именно с этим путём) и тонкая обёртка с `#[tauri::command]` — атрибут в крейт не
