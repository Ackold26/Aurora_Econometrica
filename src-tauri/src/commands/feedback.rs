///
/// 🔴 Поправка 13.09.2026: имя поля Яндекс Форм — это «Идентификатор вопроса» в настройках
/// вопроса, и его МОЖНО задать самому. По умолчанию там `answer_short_text_12345`, но поле
/// редактируемое — поэтому имена ниже читаемые, а не выданные сервисом. Прежняя редакция этого
/// комментария утверждала обратное («угадать нельзя») и была неверна.
/// Менять адрес и имена только здесь: ни одно другое место их не знает.
/// Связка проверена двумя живыми отправками 13.09.2026: предзаполнение доезжает, кириллица в
/// значениях не портится.
const FEEDBACK_FORM_URL: &str = "https://forms.yandex.ru/cloud/6aa6912e6d2d73e851bbccda/";
const FIELD_PRODUCT: &str = "produkt";
const FIELD_VERSION: &str = "versiya";
const FIELD_MACHINE: &str = "licenziya";
const FIELD_SENT_AT: &str = "vremya";
/// Версия Windows (без имени машины) — берётся из `diagnostics::os_version_summary()`.
const FIELD_SYSTEM: &str = "sistema";
/// Шаг мастера, на котором был человек — знает только фронтенд, приходит параметром команды.
const FIELD_SCREEN: &str = "ekran";
/// Текст последней ошибки — тоже параметром с фронтенда, вычищенный `sanitize_error_text`.
const FIELD_ERROR: &str = "oshibka";

/// Метка незаполненной заглушки. Одна на все пять значений выше.
const PLACEHOLDER_MARK: &str = "ПОДСТАВИТЬ";

/// Есть ли среди значений хоть одна незаполненная заглушка.
///
/// Вынесено отдельной функцией от значений, а не от постоянных: так её проверяет сторож и после
/// того, как настоящие адрес и имена полей будут подставлены.
fn any_placeholder(values: &[&str]) -> bool {
    values.iter().any(|value| value.contains(PLACEHOLDER_MARK))
}

/// Подставлены ли настоящие адрес и имена полей.
fn form_is_connected() -> bool {
    !any_placeholder(&[
        FEEDBACK_FORM_URL,
        FIELD_PRODUCT,
        FIELD_VERSION,
        FIELD_MACHINE,
        FIELD_SENT_AT,
    ])
}

/// Закодировать значение для подстановки в адрес.
///
/// 🔴 Своими руками, без новой зависимости (ADR-050: крупных внешних зависимостей в продукт не
/// тащим без нужды). Незакодированным оставляем только то, что безопасно по RFC 3986:
/// латиницу, цифры и `-_.~`. Всё прочее уходит тройками `%XX` ПО БАЙТАМ UTF-8 — иначе русский
/// текст и знак `+` поехали бы в адрес как есть.
///
/// Зачем это вообще: отпечаток шестнадцатеричный и пострадать не может, а вот версия способна
/// содержать `+` (например `2.5.2+build.7`), и в адресе `+` значит ПРОБЕЛ — форма получила бы
/// другую версию, не заметив подмены. Время содержит пробелы и скобки, программа — дефисы.
fn percent_encode(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for byte in value.as_bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(*byte as char)
            }
            other => out.push_str(&format!("%{other:02X}")),
        }
    }
    out
}

/// Предел текста последней ошибки в обращении.
///
/// 🔴 Зачем именно предел (задача владельца 13.09.2026): адрес с семью полями способен
/// перерасти предел, который принимает системный вызов открытия браузера — тогда браузер
/// молча не откроется. 300 знаков — ориентир с запасом даже после процентного кодирования
/// (кириллица раздувается втрое: 300 знаков кириллицы дают около 900 байт в адресе).
const ERROR_TEXT_MAX_CHARS: usize = 300;

/// Путь к файлу в тексте ошибки. Начало пути опознаётся четырьмя видами: буква диска с
/// двоеточием и слешем — прямым или обратным (`C:\...` либо `C:/...`), сетевой путь
/// (`\\сервер\...`), относительный от текущей папки (`.\...`, `..\...`) и относительный без
/// точек (`Users\Иван Петров\...`).
///
/// 🔴 Пробел из стоп-класса убран (находка внешнего аудита 13.09.2026): пути Windows пробелы
/// в именах папок и учётных записей несут сплошь и рядом (`C:\Users\Иван Петров\...`), и
/// граница по пробелу обрезала путь на середине, оставляя хвост — включая фамилию — в тексте,
/// который уезжает в стороннюю форму.
///
/// 🔴 Третья редакция (находки 1 и 7 внешнего аудита 14.09.2026). Вторая запрещала пробел в
/// ПОСЛЕДНЕМ сегменте — чтобы метка `[путь]` не съедала причину отказа. Цена запрета не была
/// измерена, а последний сегмент — это имя файла: `C:\data\мой отчёт Кагоцел.xlsx` резалось по
/// первому пробелу, и «отчёт Кагоцел.xlsx» — бренд и год чужого проекта — уезжало в стороннюю
/// форму. Так же терялась фамилия владельца учётной записи у пути к ПАПКЕ
/// (`C:\Users\Иван Петров` → «[путь] Петров»).
///
/// Спор «путь против причины отказа» решает теперь не пробел, а РАСШИРЕНИЕ — два хвоста:
/// * с расширением — всё до точки, за которой 1–8 букв или цифр; пробелы, скобки и запятые
///   внутри допустимы. `мой отчёт Кагоцел.xlsx`, `отчёт, финальный.xlsx`,
///   `Иванов (админ)\план.xlsx` уходят в метку целиком, а `план.csv не найден на диске`
///   останавливается сразу за `план.csv` — причина отказа остаётся в тексте;
/// * без расширения (путь к ПАПКЕ) — жадно до кавычки, угловой скобки, запятой, точки с
///   запятой, двоеточия, знака, запрещённого в именах Windows (`|`, `*`, `?`), перевода строки
///   или конца текста: `C:\Users\Иван Петров` уходит целиком.
///
/// Двоеточие в стоп-классе обоих хвостов — не только пунктуация: без него путь дожёвывает до
/// буквы ВТОРОГО диска через пробел-разделитель («…a.csv в D:\Backup\…»), склеивая два разных
/// пути одной фразы в одну метку. Хвостовой знак препинания (точка, запятая и т.п.) в самом
/// конце совпадения — не часть пути, обрезается отдельно в `sanitize_error_text`.
///
/// Относительный путь без точек опознаётся ТОЛЬКО по обратному слешу (`Users\...`): прямой
/// слеш живёт в русском тексте сам по себе («и/или», «км/ч», «п.5/2»), и разрешение прямого
/// слеша здесь накрывало бы меткой обычные слова.
///
/// 🔴 Чем платим — осознанно, в пользу защиты данных. Путь к ПАПКЕ, за которым БЕЗ запятой
/// идёт причина отказа («C:\Users\Иван доступ запрещён»), уходит в метку вместе с причиной:
/// «Иван доступ запрещён» синтаксически неотличимо от папки с пробелами, и выбор тут между
/// лишней вычисткой и утечкой фамилии. Слово с точкой внутри после пути («…\отчёт.xlsx.
/// Проверьте версию 2.5») тоже поглощается — жадная граница тянется до ПОСЛЕДНЕГО расширения.
/// Оба случая — лишняя вычистка, не утечка.
fn path_pattern() -> &'static regex::Regex {
    static PATTERN: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
    PATTERN.get_or_init(|| {
        regex::Regex::new(
            r#"(?:[A-Za-z]:[\\/]|\\\\|\.{1,2}[\\/]|[^\s"'<>|*?:\\/]+\\)(?:[^"'<>|*?:\r\n]*\.[A-Za-zА-Яа-яЁё0-9]{1,8}|[^"'<>|*?:,;\r\n]*)"#,
        )
        .expect("путь-паттерн верен")
    })
}

/// Вычистить путь к файлу из текста ошибки и обрезать его до безопасной длины (INV-38 +
/// предел адреса выше).
///
/// 🔴 Путь способен назвать человека: `C:\Users\Иван\Documents\отчёт.xlsx` несёт имя учётной
/// записи. Вырезаем не молча, а меткой — так причина отказа остаётся понятной («не удалось
/// открыть [путь]» читается, голое «не удалось открыть» — нет). Хвостовой знак препинания
/// (`.`, `,`, `;`, `:`, `!`, `?`), случайно захваченный жадным совпадением на конце фразы,
/// метка не поглощает — он остаётся после неё, иначе точка в конце предложения пропадает.
fn sanitize_error_text(text: &str) -> String {
    let scrubbed = path_pattern().replace_all(text, |caps: &regex::Captures| {
        let matched = &caps[0];
        let path_part = matched.trim_end_matches(['.', ',', ';', ':', '!', '?']);
        let trailing_punct = &matched[path_part.len()..];
        format!("[путь]{trailing_punct}")
    });
    let char_count = scrubbed.chars().count();
    let truncated: String = scrubbed.chars().take(ERROR_TEXT_MAX_CHARS).collect();
    if char_count > ERROR_TEXT_MAX_CHARS {
        format!("{truncated}…")
    } else {
        truncated
    }
}

/// Ссылка на форму обратной связи с предзаполненными скрытыми полями.
///
/// 🔴 Состав: программа, версия, ПОЛНЫЙ отпечаток машины, время, версия Windows — всегда;
/// шаг мастера и текст ошибки — необязательно, их знает только вызывающая сторона (окно
/// ошибки в мастере). Отпечаток целиком, а не первыми 12 знаками, как в журнале входа: в
/// нашей модели лицензия опознаётся парой «отпечаток + программа», и оба поля нужны, чтобы
/// найти запись в панели управления. Персональными данными отпечаток не является — это хеш
/// характеристик машины, человек по нему не называется.
///
/// Ни имени пользователя, ни имени машины, ни путей к файлам здесь нет и быть не должно
/// (INV-38): текст ошибки проходит через `sanitize_error_text`. Состав собирается целиком в
/// этой функции — значит и проверять его надо в одном месте, сторожем ниже.
fn feedback_form_link(ekran: Option<&str>, oshibka: Option<&str>) -> String {
    // Незнакомое имя пакета `detect_product` отдаёт как "unknown" — это потеря атрибуции ровно
    // там, где она и нужна. Подставляем сырое имя пакета: оно хотя бы называет сборку.
    let product = match crate::commands::online_auth::detect_product() {
        "unknown" => env!("CARGO_PKG_NAME"),
        known => known,
    };
    let machine = crate::crypto::fingerprint::get_machine_fingerprint()
        .map(|fp| crate::crypto::fingerprint::hash_fingerprint(&fp))
        // Отказ в подсчёте отпечатка обращение не отменяет: форма без метки машины полезнее,
        // чем закрытая дорога. Причина при этом названа, а не скрыта пустотой.
        .unwrap_or_else(|_| "определить не удалось".to_string());
    let sent_at = chrono::Local::now().format("%d.%m.%Y %H:%M (%:z)").to_string();
    let system = crate::commands::diagnostics::os_version_summary();

    // Разделитель — `?` или `&`: у адреса формы могут быть свои параметры.
    let separator = if FEEDBACK_FORM_URL.contains('?') { '&' } else { '?' };

    let mut link = format!(
        "{}{}{}={}&{}={}&{}={}&{}={}&{}={}",
        FEEDBACK_FORM_URL,
        separator,
        FIELD_PRODUCT,
        percent_encode(product),
        FIELD_VERSION,
        percent_encode(env!("CARGO_PKG_VERSION")),
        FIELD_MACHINE,
        percent_encode(&machine),
        FIELD_SENT_AT,
        percent_encode(&sent_at),
        FIELD_SYSTEM,
        percent_encode(&system),
    );

    // Необязательные поля уходят, только когда есть что сказать: пустое значение бесполезно
    // так же, как отсутствующее, а для формы — короче ссылка.
    if let Some(screen) = ekran.filter(|s| !s.trim().is_empty()) {
        link.push_str(&format!("&{FIELD_SCREEN}={}", percent_encode(screen)));
    }
    if let Some(error_text) = oshibka.filter(|s| !s.trim().is_empty()) {
        let cleaned = sanitize_error_text(error_text);
        link.push_str(&format!("&{FIELD_ERROR}={}", percent_encode(&cleaned)));
    }

    link
}

/// Открыть форму обратной связи в браузере с предзаполненными скрытыми полями.
///
/// `ekran` и `oshibka` — необязательные: страница настроек их знать не может (там просто
/// кнопка «Обратная связь»), а окно ошибки в мастере передаёт оба сама, ничего не спрашивая
/// у человека. Возвращает открытую ссылку — она нужна для разбора и для живого прогона.
/// Отказ не ломает работу программы: обратная связь не основная её обязанность.
#[tauri::command]
pub async fn open_feedback_form(ekran: Option<String>, oshibka: Option<String>) -> Result<String, String> {
    if !form_is_connected() {
        warn!("Обратная связь: адрес формы не подставлен — открывать нечего");
        return Err(coded(
            ErrorCode::FB001,
            "Форма обратной связи пока не подключена к этой сборке. \
             Напишите нам на sales@auroraai.pro – ответим так же.",
        ));
    }

    let link = feedback_form_link(ekran.as_deref(), oshibka.as_deref());
    info!("Обратная связь: открываю форму в браузере");

    tauri_plugin_opener::open_url(&link, None::<&str>).map_err(|e| {
        warn!("Обратная связь: открыть браузер не удалось: {e}");
        coded(
            ErrorCode::FB001,
            "Не удалось открыть браузер с формой обратной связи. \
             Напишите нам на sales@auroraai.pro – ответим так же.",
        )
    })?;

    Ok(link)
}

