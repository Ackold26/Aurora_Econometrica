    /// 🔴 Находка 1 внешнего аудита 14.09.2026: пробел в ПОСЛЕДНЕМ сегменте пути.
    ///
    /// Двенадцать прежних сценариев подобраны так, что пробел всегда стоит в СРЕДНЕМ сегменте —
