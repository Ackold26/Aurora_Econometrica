    /// 🔴 Обратная сторона вычистки: текст БЕЗ пути страдать не должен, а причина отказа обязана
    /// пережить метку. Вычистка, которая съедает половину сообщения, лечит утечку ценой
    /// непонятного обращения — человек жалуется, а на что, прочесть нельзя.
    ///
    /// Оси мутации: (1) разрешить прямой слеш началом относительного пути — краснеет на «и/или»
    /// и «км/ч»; (2) убрать запятую из стоп-класса хвоста без расширения — краснеет на «повторите
    /// позже»; (3) разрешить хвосту без расширения перешагивать перевод строки — краснеет на
    /// строке трассировки.
    #[test]
    fn sanitize_error_text_keeps_everything_that_is_not_a_path() {
        // 1. Проза со слешами — ни одного пути в ней нет.
        let текст = "скорость 50 км/ч, обучение и/или прогноз не запустились";
        assert_eq!(sanitize_error_text(текст), текст);

        // 2. Имя файла без пути вычистке не подлежит — вычищаем ПУТИ, а не всякое слово с точкой.
        let текст = "Ошибка: план.csv не найден на диске";
        assert_eq!(sanitize_error_text(текст), текст);

        // 3. Обычное сообщение об отказе модели.
        let текст = "Не удалось обучить модель: мало наблюдений (12 из 24)";
        assert_eq!(sanitize_error_text(текст), текст);

        // 4. Путь к ПАПКЕ с пробелом, за ним причина через запятую: папка уходит целиком,
        // причина остаётся.
        assert_eq!(
            sanitize_error_text(r"не удалось открыть C:\Users\Иван Петров, повторите позже"),
            "не удалось открыть [путь], повторите позже"
        );

        // 5. Причина отказа сразу за именем файла, БЕЗ запятой — держится на расширении.
        assert_eq!(
            sanitize_error_text(r"Ошибка: C:\Users\Иван Петров\план.csv не найден на диске"),
            "Ошибка: [путь] не найден на диске"
        );

        // 6. Многострочная трассировка: каждая строка чистится своей меткой, перевод строки
        // границей остаётся, и название исключения не теряется.
        let трассировка = format!(
            "{}\n{}",
            r#"Ошибка чтения файла: "C:\data\Иванов\отчёт.py""#,
            r"FileNotFoundError: C:\data\Иванов\бюджет 2027.xlsx"
        );
        let cleaned = sanitize_error_text(&трассировка);
        assert!(!cleaned.contains("Иванов"), "утечка имени в трассировке: {cleaned}");
        assert_eq!(
            cleaned,
            "Ошибка чтения файла: \"[путь]\"\nFileNotFoundError: [путь]"
        );

        // 7. Длинный текст с путём: путь вычищен, а обрезка по пределу работает поверх вычистки,
        // а не вместо неё.
        let длинный = format!(
            r"Файл не найден: C:\data\Иванов\отчёт.xlsx причина неизвестна {}",
            "я".repeat(ERROR_TEXT_MAX_CHARS)
        );
        let cleaned = sanitize_error_text(&длинный);
        assert!(!cleaned.contains("Иванов"), "утечка имени в длинном тексте: {cleaned}");
        assert!(
            cleaned.starts_with("Файл не найден: [путь] причина неизвестна"),
            "начало длинного текста пострадало: {cleaned}"
        );
        assert!(
            cleaned.chars().count() <= ERROR_TEXT_MAX_CHARS + 1,
            "длинный текст не обрезан до предела: {} знаков",
            cleaned.chars().count()
        );
    }

