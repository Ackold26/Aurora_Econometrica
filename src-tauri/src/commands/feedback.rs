/// панели управления. Персональными данными отпечаток не является — это хеш характеристик
/// машины. Ни имени пользователя, ни имени машины, ни путей к файлам здесь нет (INV-38).
///
/// Вид рассчитан на чтение в письме с телефона: короткая подпись, каждое поле на своей строке.
///
/// 🔴 Почему хвост собирается ЗДЕСЬ, а не в общем крейте: `aurora_core` подключён по метке из
/// хранилища (`aurora_core-v0.1.0` в `Cargo.toml`), и его правка потребовала бы новой метки.
/// А названия продукта и отпечатка в крейте и нет — они живут в самой программе. Граница
/// проходит ровно так: крейт отправляет, программа рассказывает о себе.
fn attribution_tail() -> String {
    let product = match crate::commands::online_auth::detect_product() {
        "unknown" => env!("CARGO_PKG_NAME"),
        known => known,
    };
    let machine = crate::crypto::fingerprint::get_machine_fingerprint()
        .map(|fp| crate::crypto::fingerprint::hash_fingerprint(&fp))
        .unwrap_or_else(|_| "определить не удалось".to_string());

    format!(
        "Программа: {} {}\nМашина: {}\nОтправлено: {}\n\nСообщение:\n",
        product,
        env!("CARGO_PKG_VERSION"),
        machine,
        chrono::Local::now().format("%d.%m.%Y %H:%M (%:z)")
    )
}

/// Отправить обращение человека в нашу форму обратной связи. Тело — в `aurora_core::feedback::submit`.
///
/// 🔴 Поле контакта убрано по решению владельца 13.09.2026: персональных данных программа больше
/// не собирает. Общий крейт поле формы всё ещё заполняет — поэтому отдаём ему пустую строку:
/// поле уходит пустым, данных в нём нет.
///
/// 🔴 Возвращает всегда `"sent"`, а не `"recorded"`, и это честно, а не недоделка. Признак записи
/// читается в теле ответа сервиса, а тело остаётся внутри `aurora_core::feedback::submit`: он
/// отдаёт только `"ok"`, то есть «отправка не отвергнута». Утверждать запись по такому ответу
/// нельзя. Чтобы Econometrica могла говорить «записано», как остальные продукты, нужна новая
/// метка `aurora_core` с разбором признака — это решение владельца, не наше.
#[tauri::command]
pub async fn submit_feedback(category: String, message: String) -> Result<String, String> {
    let message = message.trim();

    if message.is_empty() {
        return Err("Сообщение не может быть пустым".to_string());
    }

    // Считаем ЗНАКИ, а не байты: в русском тексте байтов вдвое больше, и предел по байтам
    // отказал бы человеку на вдвое коротком тексте, не объяснив почему.
    let length = message.chars().count();
    if length > MESSAGE_MAX_CHARS {
        return Err(coded(
            ErrorCode::FB001,
            &format!(
                "Текст обращения длиннее, чем мы можем отправить: {length} знаков из {MESSAGE_MAX_CHARS}. \
                 Сократите текст – главное опишите в начале, подробности можно прислать письмом."
            ),
        ));
    }

    // Хвост встаёт ПЕРЕД текстом человека: в письме с уведомлением первым видно, откуда
    // обращение пришло, и только потом его содержание.
    let full_message = format!("{}{}", attribution_tail(), message);

    aurora_core::feedback::submit(category, full_message, String::new()).await?;
    Ok("sent".to_string())
}

