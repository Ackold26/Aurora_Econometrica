//! Мягкое удаление того, что принадлежит человеку: в корзину операционной системы,
//! а не насовсем.
//!
//! 🔴 Зачем отдельный модуль. Правовой документ поставки обещает клиенту, что программа
//! сама ничего не стирает. Обещание было ложным: папка приёма на Рабочем столе чистилась
//! обычным `remove_file` при каждом запуске и при каждом закрытии сессии, а вместе с ней
//! уходили файлы, которые человек положил туда сам. Восстановить их было неоткуда.
//!
//! 🔴 Что сюда НЕ относится. Затирание расшифрованных файлов кабинета
//! (`session::manager::secure_delete_dir`, `session::cleanup`) обязано оставаться
//! безвозвратным: там персональные данные, и перевод их в корзину — не починка, а утечка.
//! То же для служебных временных файлов программы (промежуточные `.tmp`, недокачанные
//! `.part`, каталоги сборки): человек их не создавал, и засорять ими его корзину незачем.
//! Граница между двумя видами удаления проверяется сторожем в конце файла.
//!
//! 🔴 Что делаем, если корзина недоступна (сетевой диск, съёмный носитель, файловая
//! система без корзины). Молчаливого отката на безвозвратное стирание здесь НЕТ, и это
//! решение, а не упущение. Цена «файл остался лежать» — мелкое неудобство: человек уберёт
//! его сам, папка и так его. Цена «файл стёрт насовсем» — невосполнимая потеря его работы
//! и ровно то ложное обещание, ради которого написан этот модуль. Асимметрия однозначная,
//! поэтому при отказе корзины файл остаётся на месте, а причина уходит в журнал с полным
//! путём; в местах, где удаление заказал сам человек, отказ возвращается ему текстом.

use log::{info, warn};
use std::path::Path;

/// Убрать в корзину файл или папку, принадлежащие человеку.
///
/// Отсутствующий путь — не ошибка: удалять нечего, значит цель достигнута.
/// Отказ не глушится никогда: предупреждение с путём и причиной пишется здесь, внутри,
/// поэтому вызывающему остаётся решить лишь одно — сообщать ли о нём человеку.
pub fn soft_delete(path: &Path) -> Result<(), String> {
    if !path.exists() {
        return Ok(());
    }
    match trash::delete(path) {
        Ok(()) => {
            info!("В корзину: {}", path.display());
            Ok(())
        }
        Err(e) => {
            warn!(
                "Не удалось переместить в корзину {} — {e}. Файл ОСТАВЛЕН на месте: \
                 стирать его насовсем программа не станет",
                path.display()
            );
            Err(format!(
                "не удалось переместить в корзину: {e}. Файл остался на месте – \
                 уберите его вручную, если он больше не нужен"
            ))
        }
    }
}

#[cfg(test)]
mod trash_availability_probe {
    use super::*;

    /// Зонд среды, а не проверка нашей логики: корзина — это служба системы, и без неё
    /// все остальные проверки этого модуля недоказательны. Если он покраснел на машине
    /// сборки — красный здесь означает «корзина недоступна в этой среде», и разбираться
    /// нужно со средой, а не с кодом.
    #[test]
    fn korzina_dostupna_v_srede_sborki() {
        let dir = tempfile::tempdir().unwrap();
        let f = dir.path().join("проба.txt");
        std::fs::write(&f, b"proba").unwrap();
        soft_delete(&f).expect("корзина недоступна в этой среде");
        assert!(!f.exists(), "файл обязан исчезнуть из папки");
    }

    /// Отсутствующий путь — не отказ.
    #[test]
    fn otsutstvuyushchiy_put_ne_oshibka() {
        let dir = tempfile::tempdir().unwrap();
        soft_delete(&dir.path().join("нет-такого.txt")).unwrap();
    }
}

// ── Сторож границы: что в корзину, а что насовсем ────────────────────────────
//
// 🔴 Сторож намеренно читает ИСХОДНЫЙ ТЕКСТ отгружаемых файлов через `include_str!`,
// а не свою копию правил и не поведение на временной папке. Причина ровно одна: дефект,
// против которого он поставлен, возвращается правкой одной строки в чужой функции, и
// поймать это можно только глядя на ту самую строку. Приём в доме уже принят —
// `durable_store.rs` сторожит свой запрет тем же способом.
//
// Сторож обязан краснеть в ОБЕ стороны:
//   · клиентское удаление вернули на безвозвратное → `klientskie_udaleniya_...`;
//   · затирание персональных данных перевели в корзину → `zatiranie_pdn_...`.

#[cfg(test)]
mod guard_soft_delete_boundary {
    const MANAGER_RS: &str = include_str!("session/manager.rs");
    const CLEANUP_RS: &str = include_str!("session/cleanup.rs");
    const LIB_RS: &str = include_str!("lib.rs");
    const BRAND_RS: &str = include_str!("commands/brand.rs");
    const CAMPAIGN_RS: &str = include_str!("commands/campaign.rs");

    /// Имена безвозвратного удаления. Сторож ищет ИМЯ ФУНКЦИИ как отдельное слово, а не
    /// написание `fs::имя`.
    ///
    /// 🔴 Выстрадано мутацией: сторож, искавший подстроку `fs::remove_file`, слеп к
    /// `use std::fs::remove_file;` в шапке и короткому `remove_file(path)` в теле —
    /// поведение при этом ровно то, которое мы чиним. Заплата под конкретный синоним
    /// закрыла бы носитель вместо класса, поэтому правило переписано по существу:
    /// запрещено ИМЯ, в любом написании, плюс запрещён его ввоз в шапку файла (это
    /// ловит и переименование при ввозе — `use std::fs::remove_file as unlink`).
    const BEZVOZVRATNYE: &[&str] = &["remove_file", "remove_dir_all", "remove_dir"];

    /// Встречается ли `name` в `code` как отдельное слово (а не куском другого имени).
    /// Без внешних зависимостей: соседние символы не должны годиться для имени.
    fn est_slovo(code: &str, name: &str) -> bool {
        fn chast_imeni(c: char) -> bool {
            c.is_alphanumeric() || c == '_'
        }
        let mut ot = 0usize;
        while let Some(i) = code[ot..].find(name) {
            let start = ot + i;
            let end = start + name.len();
            let levo_ok = code[..start].chars().next_back().is_none_or(|c| !chast_imeni(c));
            let pravo_ok = code[end..].chars().next().is_none_or(|c| !chast_imeni(c));
            // `remove_dir` как слово не должно ловиться внутри `remove_dir_all`: правое
            // соседство `_` отсекает это само.
            if levo_ok && pravo_ok {
                return true;
            }
            ot = start + 1;
        }
        false
    }

    /// Строки тела, в которых встречается запрещённое имя, — чтобы сообщение сторожа
    /// показывало ту самую строку, а не только факт.
    fn stroki_s_imenem<'a>(body: &'a str, name: &str) -> Vec<&'a str> {
        body.lines().filter(|l| est_slovo(l, name)).collect()
    }

    /// Тело функции от её сигнатуры до парной закрывающей скобки.
    /// Искать запрет по всему файлу нельзя: в тех же файлах законных безвозвратных
    /// удалений служебных файлов десятки, и сторож на весь файл краснел бы всегда.
    fn telo<'a>(code: &'a str, signature: &str) -> &'a str {
        let start = code
            .find(signature)
            .unwrap_or_else(|| panic!("сигнатура не найдена: {signature}"));
        let tail = &code[start..];
        let open = tail
            .find('{')
            .unwrap_or_else(|| panic!("у {signature} нет тела"));
        let mut depth = 0usize;
        for (i, c) in tail[open..].char_indices() {
            match c {
                '{' => depth += 1,
                '}' => {
                    depth -= 1;
                    if depth == 0 {
                        return &tail[open..=open + i];
                    }
                }
                _ => {}
            }
        }
        panic!("не закрыто тело {signature}");
    }

    /// Семь мест, где удаляется то, что принадлежит человеку. Проверяется ДВА свойства,
    /// и оба обязательны — по отдельности каждое обходится:
    ///
    /// * «что должно быть» — удаление идёт через единственную функцию `soft_delete`.
    ///   Устойчиво к синонимам: перечень разрешённых путей держим мы сами;
    /// * «чего не должно быть» — ни одного вызова безвозвратного удаления по ИМЕНИ, в
    ///   любом написании. Без этой половины мимо проходит откат «не вышло в корзину —
    ///   сотру насовсем» рядом с исправным вызовом: `soft_delete` в теле есть, значит
    ///   первая половина зелёная, а дефект вернулся целиком. Случай не выдуманный —
    ///   ровно так написан `commands/project.rs:508`.
    ///
    /// Исключение ровно одно и названо поимённо: в `brand_delete` рядом с удалением папки
    /// бренда законно стирается насовсем служебный указатель «какой бренд выбран»
    /// (`active_brand.json`) — он не данные человека. Разрешение выдано не имени функции,
    /// а конкретной строке: безвозвратное удаление там обязано стоять в одной строке с
    /// `active_path`, иначе сторож краснеет.
    #[test]
    fn klientskie_udaleniya_tolko_v_korzinu() {
        let mesta: &[(&str, &str, &str, Option<&str>)] = &[
            (MANAGER_RS, "fn clear_inbox(", "очистка папки приёма на Рабочем столе", None),
            (LIB_RS, "fn delete_inbox_file(", "удаление файла из папки приёма", None),
            (LIB_RS, "fn delete_export_file(", "удаление файла из папки выдачи", None),
            (LIB_RS, "fn clear_workspace_dirs(", "очистка папки приёма при запуске", None),
            (
                BRAND_RS,
                "pub async fn brand_delete(",
                "удаление бренда с документами",
                Some("active_path"),
            ),
            (BRAND_RS, "pub async fn brand_delete_doc(", "удаление документа бренда", None),
            (CAMPAIGN_RS, "pub fn workflow_delete(", "удаление сценария кампании", None),
        ];

        for (code, signature, chto, isklyuchenie) in mesta {
            let body = telo(code, signature);

            for imya in BEZVOZVRATNYE {
                for stroka in stroki_s_imenem(body, imya) {
                    let razresheno = isklyuchenie.is_some_and(|marker| stroka.contains(marker));
                    assert!(
                        razresheno,
                        "{signature} ({chto}): безвозвратное «{imya}» в строке\n    {}\n\
                         Файлы человека уходят ТОЛЬКО в корзину — \
                         crate::soft_delete::soft_delete. Отката на безвозвратное стирание \
                         здесь нет намеренно: при отказе корзины файл остаётся на месте.",
                        stroka.trim()
                    );
                }
            }

            assert!(
                body.contains("soft_delete::soft_delete("),
                "{signature} ({chto}): удаление есть, а вызова мягкого удаления нет"
            );
        }
    }

    /// Вторая половина того же правила, на уровне файла: безвозвратное удаление в
    /// клиентских файлах зовётся только полным путём `std::fs::…` и никогда не ввозится
    /// в шапку. Тогда короткое имя в теле не может оказаться удалением из стандартной
    /// библиотеки, и проверка тел выше становится полной.
    ///
    /// Это же правило ловит переименование при ввозе (`use std::fs::remove_file as unlink`),
    /// от которого проверка по имени сама по себе слепа.
    #[test]
    fn bezvozvratnoe_udalenie_ne_vvozitsya_v_shapku() {
        let fayly: &[(&str, &str)] = &[
            (MANAGER_RS, "session/manager.rs"),
            (LIB_RS, "lib.rs"),
            (BRAND_RS, "commands/brand.rs"),
            (CAMPAIGN_RS, "commands/campaign.rs"),
        ];

        for (code, imya_fayla) in fayly {
            for stroka in code.lines() {
                let s = stroka.trim();
                if !s.starts_with("use ") {
                    continue;
                }
                for imya in BEZVOZVRATNYE {
                    assert!(
                        !est_slovo(s, imya),
                        "{imya_fayla}: ввоз безвозвратного удаления в шапку — «{s}». \
                         В этом файле есть удаления файлов человека; безвозвратное удаление \
                         служебных файлов здесь зовётся только полным путём std::fs::…, \
                         иначе короткое имя в теле не отличить от него."
                    );
                }
            }
        }
    }

    /// Обратная сторона границы: затирание персональных данных обязано остаться
    /// безвозвратным. Корзина хранит содержимое файла целиком и доступна кому угодно за
    /// этим столом — перевод затирания в корзину не починка, а утечка (INV-38).
    #[test]
    fn zatiranie_pdn_nikogda_ne_v_korzinu() {
        let mesta: &[(&str, &str, &str)] = &[
            (MANAGER_RS, "pub(crate) fn secure_delete_dir(", "затирание каталога сессии"),
            (MANAGER_RS, "pub(crate) fn secure_delete_file(", "затирание файла кабинета"),
            (MANAGER_RS, "fn sync_dir_to(", "зеркало во временный каталог сессии"),
        ];

        for (code, signature, chto) in mesta {
            let body = telo(code, signature);
            assert!(
                !body.contains("trash::") && !body.contains("soft_delete"),
                "{signature} ({chto}): здесь корзина запрещена — расшифрованные данные \
                 клиента обязаны стираться безвозвратно (INV-38)"
            );
        }

        assert!(
            !CLEANUP_RS.contains("trash::") && !CLEANUP_RS.contains("soft_delete"),
            "session/cleanup.rs: уборка осиротевших каталогов сессий обязана затирать \
             данные, а не складывать их в корзину (INV-38)"
        );
    }
}
