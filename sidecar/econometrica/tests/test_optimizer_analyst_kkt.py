# Параметры переноса и насыщения, которые ставит обучение OLS (engines/ols_modeler.py).
# Данные порождаются ТЕМИ ЖЕ преобразованиями, что использует обучение, — тогда
# коэффициенты каналов восстанавливаются точно и задача распределения получается
# ровно той, какую задумывали, без шумовых сюрпризов вроде отрицательной отдачи.
РАСПАД = 0.5
АЛЬФА = 1.5
ГАММА = 0.5

КАНАЛЫ = ('tv', 'ooh', 'online_video', 'performance')

# Траты за период, порядок 1e7–1e8 → бюджет за 48 периодов порядка 1e9. Именно этот
# масштаб денежной оси и «расплющивал» целевую функцию для SLSQP до правки.
УРОВНИ = {'tv': 9.0e7, 'ooh': 2.5e7, 'online_video': 1.2e7, 'performance': 8.0e6}

# Отдача на рубль относительно ТВ: наружная в 1,5 раза выше (значит оптимум
# перебросит часть денег с ТВ на неё, но обоих оставит внутри границ), онлайн-видео
# и performance в 5–6 раз выше (упрутся в потолок).
ОТНОСИТЕЛЬНАЯ_ОТДАЧА = {'tv': 1.0, 'ooh': 1.5, 'online_video': 5.0, 'performance': 6.0}

БАЗА_KPI = 4.0e9        # немедийный вклад за период
МАСШТАБ_KPI = 1.0e9     # цена единицы отклика в KPI
ПЕРИОДОВ = 48


def _обучающие_данные(путь: Path) -> Path:
    """Данные, порождённые преобразованиями продукта: перенос → насыщение → отклик."""
    rng = np.random.RandomState(20260909)
    df = pd.DataFrame({'Дата': pd.date_range('2024-01-06', periods=ПЕРИОДОВ, freq='W')})
    for канал in КАНАЛЫ:
        df[канал] = rng.uniform(0.4, 1.6, ПЕРИОДОВ) * УРОВНИ[канал]

    отклик = np.full(ПЕРИОДОВ, БАЗА_KPI)
    for канал in КАНАЛЫ:
        перенесённый = apply_adstock(df[канал].values.astype(float), 'geometric', {'alpha': РАСПАД})
        средний = float(перенесённый.mean())
        насыщенный = hill_function(перенесённый / средний, АЛЬФА, ГАММА)
        # β подобрана так, чтобы β/уровень трат дал заданную относительную отдачу.
        beta = ОТНОСИТЕЛЬНАЯ_ОТДАЧА[канал] * УРОВНИ[канал] / 1.0e7
        отклик = отклик + beta * насыщенный * МАСШТАБ_KPI
    # Шум мал намеренно: восстановление коэффициентов не должно быть лотереей.
    df['sales'] = отклик + rng.normal(0, БАЗА_KPI * 1.0e-3, ПЕРИОДОВ)

    файл = путь / 'data.xlsx'
    df.to_excel(файл, index=False)
    return файл


@pytest.fixture(scope='session')
def проект(tmp_path_factory) -> str:
    """Проект с обученной моделью — вход для `engines.optimizer.optimize`."""
    каталог = tmp_path_factory.mktemp('оптимизатор_ккт')
    файл = _обучающие_данные(каталог)

