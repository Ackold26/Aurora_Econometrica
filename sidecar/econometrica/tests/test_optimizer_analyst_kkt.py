"""Сторож условия оптимума в АНАЛИТИЧЕСКОМ режиме оптимизатора (09.09.2026).

Зачем этот файл появился. Замером через перехват вызовов установлено: из всего
набора тестов движка НИ ОДИН не вызывал `engines.optimizer.optimize`. Единственный
тест, который вообще решал задачу распределения (`test_optimizer_planning_mode`),
импортирует решатель сам и считает СВОЮ модельную задачу — код продукта при этом
не исполняется. В этой слепой зоне и прожил дефект: нормировка переменных для
SLSQP включалась только в режиме планирования, а в аналитическом режиме переменные
порядка 1e9 при точности решателя 1e-7 делали целевую функцию «плоской». Решатель
останавливался почти сразу и писал `optimization_converged = True` в неоптимальной
точке.

Почему сторожем взято условие оптимума, а не эталонные числа. Признак сходимости
решателя — его собственное мнение о себе, и именно оно врало. Проверяемое здесь
условие Каруша–Куна–Таккера внешнее и неоспоримое: в оптимуме у каналов, стоящих
ВНУТРИ своих границ, предельные отдачи обязаны совпадать — иначе рубль, снятый с
канала с меньшей отдачей и отданный каналу с большей, увеличил бы отклик, то есть
точка не оптимальна. Каналы, упёршиеся в границу, из сравнения исключаются: у них
отдача может быть выше, и это ровно то, что условия ККТ разрешают.

Сторож проверен мутацией: с возвращённым дефектным условием (`planning_mode and
money_target > 1.0`) он краснеет — предельные отдачи внутренних каналов расходятся
в разы при `optimization_converged = True`.

Задача поставлена так, чтобы сеть была натянута: два канала (`online_video`,
`performance`) по построению эффективнее и упираются в потолок, а два (`tv`, `ooh`)
остаются внутри границ и обязаны сравняться по предельной отдаче. Если внутренних
каналов окажется меньше двух — сравнивать нечего, и тест об этом честно падает,
а не проходит впустую.
"""

