def test_полностью_зажатые_границы_не_роняют_расчёт(проект):
    """Границы «ровно 100 %» у всех каналов обязаны считаться, а не падать.

    09.09.2026, найдено адверсариальной проверкой радиуса влияния правки нормировки.
    Когда нижняя граница равна верхней у ВСЕХ каналов, решать нечего: scipy сообщает
    «All independent variables were fixed by bounds» и возвращает результат БЕЗ поля
    `nit`. Обёртка нормированной ветви читала это поле напрямую, `AttributeError` не
    входил в перехват и вылетал из `optimize()` наружу — запрос клиента падал целиком.

    Дефект внесён самой правкой: до неё нормированная ветвь работала только в режиме
    планирования, где такая конфигурация отбивается проверкой бюджета раньше. То есть
    общая нормировка сделала ранее недостижимое падение достижимым в режиме по умолчанию.

    Тест обязан краснеть: вернуть `self.nit = inner.nit` в `_ScaledResult` —
    падение воспроизводится стабильно (проверено мутацией).
    """
    from engines.optimizer import optimize

    результат = optimize(
        {'total_budget': None, 'min_pct': 100.0, 'max_pct': 100.0},
        str(проект),
    )

    assert результат.get('status') == 'ok', (
        f"зажатые границы обязаны считаться, а не падать: {результат.get('error_code')}"
    )
    # Двигать нечего — распределение обязано совпасть с текущим, прирост нулевой.
    assert abs(float(результат.get('expected_lift_pct') or 0.0)) < 1e-6, (
        'при полностью зажатых границах прироста быть не может'
    )
