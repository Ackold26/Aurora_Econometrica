def test_решатель_нашёл_перераспределение_а_не_текущую_точку(проект):
    """Ложная сходимость «в стартовой точке»: решатель отдаёт текущее распределение.

    Задача построена с заведомо неоптимальным текущим сплитом, значит оптимум
    обязан отличаться от него и давать неотрицательный прирост.
    """
    from engines.optimizer import optimize

    результат = optimize({'total_budget': None, 'min_pct': 50, 'max_pct': 150}, проект)
    assert результат['status'] == 'ok', результат

    assert результат['converged_at_current'] is False, (
        'решатель вернул текущее распределение — перераспределения не найдено'
    )
    assert результат['expected_lift_pct'] >= 0
    assert результат['total_optimal_kpi'] >= результат['total_current_kpi']

    сдвиги = [abs(float(к['delta_pct'])) for к in результат['channels']]
    assert max(сдвиги) > 1.0, f'ни один канал не сдвинулся заметно: {сдвиги}'


def test_бюджет_сохранён(проект):
    """Ограничение задачи: сумма оптимального распределения равна целевому бюджету."""
    from engines.optimizer import optimize

    результат = optimize({'total_budget': None, 'min_pct': 50, 'max_pct': 150}, проект)
    assert результат['status'] == 'ok', результат

    сумма = sum(float(к['optimal_spend_money']) for к in результат['channels'])
    цель = float(результат['total_current_money'])
    assert abs(сумма - цель) / цель < 5e-3, (
        f'сумма распределения {сумма:,.0f} разошлась с бюджетом {цель:,.0f}'
    )


