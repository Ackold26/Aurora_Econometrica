# ── D. Потребители не выдают подстановку за запись ───────────────────────────

def _с_сентинелями(модель):
    """Копия модели, где заглушки загрузчика заменены на распознаваемые.

    Тип заглушки сохраняется – иначе сломается не то, что проверяем. Поля с
    заглушкой `None` пометить нечем, их держит проверка D-2.
    """
    помеченная = dict(модель)
    помеченные_поля = []
    for имя in модель.get(LOADER_DEFAULTS_KEY) or []:
        значение = модель.get(имя)
        if isinstance(значение, str):
            помеченная[имя] = СЕНТИНЕЛЬ
        elif isinstance(значение, dict):
            помеченная[имя] = {ключ: СЕНТИНЕЛЬ for ключ in значение} or {СЕНТИНЕЛЬ: СЕНТИНЕЛЬ}
        elif isinstance(значение, list):
            помеченная[имя] = [СЕНТИНЕЛЬ]
        else:
            continue
        помеченные_поля.append(имя)
    return помеченная, помеченные_поля


def _метка(стек):
    """Происхождение значения по соглашениям документа выгрузки.

    Стек – путь от корня: пары (словарь, ключ). Метка ищется от места значения
    вверх: рядом лежащий `<ключ>_origin`, общий `origin` блока либо словарь
    `origin` с меткой по имени поля (так размечены каналы). Подъём нужен для
    значений во вложенных структурах: метка стоит на всей записи, а не на
    каждом её листе.
    """
    for словарь, ключ in reversed(стек):
        if not isinstance(словарь, dict):
            continue
        if f'{ключ}_origin' in словарь:
            return словарь[f'{ключ}_origin']
        источник = словарь.get('origin')
        if isinstance(источник, str):
            return источник
        if isinstance(источник, dict) and ключ in источник:
            return источник[ключ]
    return None


# Пояснения о пропусках – единственное место документа, где заглушка загрузчика
# ЦИТИРУЕТСЯ намеренно: «в файле поля нет, программа подставила такое-то
# значение». Это и есть честный ответ, а не утверждение о записи модели.
БЛОК_ПОЯСНЕНИЙ = 'absent_fields'


def _сентинели_в_документе(узел, стек=(), путь='', найдено=None):
    """Все места документа, куда доехала подменная метка, вместе с их меткой."""
    найдено = [] if найдено is None else найдено
    if isinstance(узел, dict):
        for к, v in узел.items():
            if СЕНТИНЕЛЬ in str(к):
                найдено.append((f'{путь}.{к} (ключ)', _метка(стек + ((узел, к),))))
            _сентинели_в_документе(v, стек + ((узел, к),), f'{путь}.{к}', найдено)
    elif isinstance(узел, list):
        for i, v in enumerate(узел):
            _сентинели_в_документе(v, стек, f'{путь}[{i}]', найдено)
    elif isinstance(узел, str) and СЕНТИНЕЛЬ in узел:
        найдено.append((путь, _метка(стек)))
    return найдено


def test_выгрузка_не_называет_подставленное_записанным(прочитанная):
    """D-1. Заглушка доехала до документа – она обязана быть названа честно.

    Метка `recorded` на подставленном значении – это ровно тот дефект, из-за
    которого модель знания марки заверялась как модель продаж. Отсутствие метки
    не лучше: читатель по умолчанию считает поле записью модели.
    """
    помеченная, помеченные_поля = _с_сентинелями(прочитанная)
    assert помеченные_поля, 'ни одно поле не удалось пометить – проверка ничего не значит'

    документ = json.loads(export_model_params_json(помеченная))
    документ.pop(БЛОК_ПОЯСНЕНИЙ, None)
    вранья = [
        (путь, метка) for путь, метка in _сентинели_в_документе(документ)
        if метка in (ЗАПИСАНО, None)
    ]
    assert not вранья, (
        'подстановка загрузчика вышла в выгрузку параметров как запись модели '
        f'(поле, метка): {вранья}'
    )


def test_сертификат_не_заверяет_подставленное(прочитанная):
    """D-1 для сертификата: в хешируемом payload меток нет, значит и заглушек быть не должно."""
    помеченная, помеченные_поля = _с_сентинелями(прочитанная)
    помеченная['config'] = dict(помеченная.get('config') or {}, kpi_type='awareness')
    payload = build_cert_payload(помеченная, _разбивка(), _манифест())
    текст = json.dumps(payload, ensure_ascii=False)
    assert СЕНТИНЕЛЬ not in текст, (
        f'подстановка загрузчика уехала в заверенный payload сертификата: {текст[:400]}'
    )


def test_сертификат_не_выносит_имена_подстановок_ключами(прочитанная):
    """D-2. Держит поля с заглушкой `None`, которые сентинелем не пометить.

    Ключ в заверяемом документе – утверждение о величине. Если величина
    подставлена загрузчиком, утверждать нечего.
    """
    модель = dict(прочитанная)
    модель['config'] = dict(модель.get('config') or {}, kpi_type='awareness')
    # Версия v2.0 – чтобы дополнительная ветка сертификата тоже участвовала.
    модель['model_version'] = '2.0.0'
    модель['analysis_mode'] = 'effectiveness'
    payload = build_cert_payload(модель, _разбивка(), _манифест())

    след = set(прочитанная.get(LOADER_DEFAULTS_KEY) or [])
    вынесенные = след & set(payload)
    assert not вынесенные, (
        f'в заверенный payload вынесены подставленные загрузчиком поля: {sorted(вынесенные)}'
    )
