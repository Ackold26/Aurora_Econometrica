def test_разбор_видит_подстановки():
    """Сначала – что сам разбор жив. Пустой разбор сделал бы сторожа мёртвым."""
    имена = имена_подстановок()
    assert len(имена) >= 20, f'разбор загрузчика нашёл всего {len(имена)} подстановок – сломан'
    for якорь in ('kpi_type', 'analysis_mode', 'per_channel_input'):
        assert якорь in имена, f'разбор потерял известную подстановку {якорь}'


def test_каждая_подстановка_рассмотрена():
    """🔴 Храповик. Новая подстановка обязана быть внесена в расписку осознанно.

    Красный здесь означает: в загрузчике появилось поле, которое он подставляет
    сам, и никто не проверил, не выдают ли его заверяющие документы за запись
    обучения. Правильный ответ на красный – посмотреть потребителей этого поля
    и внести его в `РАССМОТРЕНО` с пометкой, что именно вы проверили.
    """
    имена = имена_подстановок()
    новые = имена - РАССМОТРЕНО
    исчезнувшие = РАССМОТРЕНО - имена
    assert not новые, (
        'загрузчик подставляет поля, не рассмотренные на предмет класса C-1: '
        f'{sorted(новые)}. Проверьте, что заверяющие документы (engines/json_export.py, '
        'engines/methodology_cert.py) спрашивают о них is_loader_default, и внесите '
        'их в РАССМОТРЕНО.'
    )
    assert not исчезнувшие, (
        f'в расписке числятся поля, которых загрузчик больше не подставляет: '
        f'{sorted(исчезнувшие)}. Уберите их из РАССМОТРЕНО, иначе расписка врёт.'
    )


