"""Храповик подстановок загрузчика: новая подстановка обязана быть рассмотрена.

Зачем отдельный сторож. Класс дефекта C-1 — «загрузчик подставил умолчание, а
заверяющий документ назвал его записью обучения» — выкорчёвывали в продукте уже
трижды (F-01 Critical, Ф-01 High, C-1 внешнего аудита 2026-08-16). Каждый раз
чинили ПОИМЁННО те поля, на которых поймали. Проверка класса 2026-08-17
показала, чем это кончается: след загрузчика читал один модуль из двух, а второй
— тот, что реально выдаётся клиенту, — не читал его вовсе.

Поэтому здесь имена подстановок НЕ ПЕРЕЧИСЛЕНЫ РУКАМИ, а снимаются разбором
`engines/persistence.py` по вызовам `_setdefault_tracked` (приём с `ast` в
продукте уже применяется — так `engines/json_export.py` читает `modeler.py`).
Реестр `РАССМОТРЕНО` ниже — это не источник имён, а расписка «поле проверено на
предмет C-1». Появилась новая подстановка — разбор её увидит, реестр о ней не
знает, сторож краснеет, и человек обязан прийти и посмотреть, что с этим полем
делают потребители. Это и есть храповик: он не даёт классу вернуться молча.

Четыре уровня:
    A. Реестр полон — разбор и расписка совпадают (ловит НОВУЮ подстановку).
    B. След полон — настоящий загрузчик метит следом всё, что подставил.
    C. Обход следа запрещён — подставлять мимо `_setdefault_tracked` нельзя.
    D. Поведение потребителей — заглушка загрузчика не выходит в заверяемый
       документ как запись обучения (выгрузка параметров и сертификат).

Ограничение уровня D, названное честно: подменной меткой («сентинелем»)
проверяются только поля, чья заглушка — строка, словарь или список; поля с
заглушкой `None` сентинелем не пометить, не сменив тип и не сломав потребителя
не тем. Для них работает проверка D-2: имя такого поля не выходит ключом в
хешируемый payload сертификата.
"""
