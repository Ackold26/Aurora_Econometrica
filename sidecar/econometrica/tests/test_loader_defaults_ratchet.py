# ── Разбор загрузчика ────────────────────────────────────────────────────────

def _разбор_загрузчика() -> ast.Module:
    return ast.parse(ХРАНИЛИЩЕ.read_text(encoding='utf-8'), filename=str(ХРАНИЛИЩЕ))


def имена_подстановок() -> set[str]:
    """Имена полей из вызовов `_setdefault_tracked` в функциях загрузчика.

    Имя-не-литерал — отказ, а не пропуск: молча не увиденное поле сделало бы
    сторожа мёртвым обвесом ровно в том случае, ради которого он написан.
    """
    имена: set[str] = set()
    for узел in ast.walk(_разбор_загрузчика()):
        if not isinstance(узел, ast.FunctionDef) or узел.name not in ФУНКЦИИ_ПОДСТАНОВКИ:
            continue
        for вызов in ast.walk(узел):
            if not isinstance(вызов, ast.Call):
                continue
            if getattr(вызов.func, 'id', None) != '_setdefault_tracked':
                continue
            if len(вызов.args) < 2:
                raise AssertionError(
                    f'{ФУНКЦИИ_ПОДСТАНОВКИ}: вызов _setdefault_tracked без имени поля, '
                    f'строка {вызов.lineno}'
                )
            имя = вызов.args[1]
            if not isinstance(имя, ast.Constant) or not isinstance(имя.value, str):
                raise AssertionError(
                    f'имя подставляемого поля в строке {вызов.lineno} задано не строковым '
                    f'литералом – разбор его не увидит, а сторож промолчит. Так писать нельзя.'
                )
            имена.add(имя.value)
    return имена


