def test_подстановок_мимо_следа_нет():
    """Голый `setdefault` в функциях загрузчика – подстановка без следа.

    Такое поле не увидит ни разбор, ни потребитель: оно неотличимо от записи
    обучения с первой же секунды. Именно так выглядел код до `cd7a029`.
    """
    нарушения = []
    for узел in ast.walk(_разбор_загрузчика()):
        if not isinstance(узел, ast.FunctionDef) or узел.name not in ФУНКЦИИ_ПОДСТАНОВКИ:
            continue
        for вызов in ast.walk(узел):
            if isinstance(вызов, ast.Call) and isinstance(вызов.func, ast.Attribute):
                if вызов.func.attr == 'setdefault':
                    нарушения.append(f'{узел.name}, строка {вызов.lineno}')
    assert not нарушения, (
        'подстановка мимо следа загрузчика (голый setdefault): '
        + ', '.join(нарушения)
        + '. Подставлять умолчание можно только через _setdefault_tracked.'
    )


