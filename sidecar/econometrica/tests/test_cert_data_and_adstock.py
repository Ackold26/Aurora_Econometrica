"""Отпечаток исходных данных и протокол выбора переноса в сертификате.

Два факта, которые модель записывает с 06.07.2026, доводятся до документа,
который читает клиент, – сертификата методологии в отчёте и в презентации.

Стережём следствия:
    1. факты доезжают в ОБА формата, а не в один (расхождение отчёта и
       презентации об одном расчёте – самостоятельный дефект);
    2. у модели ранней версии печатается честный статус, а тип переноса НЕ
       выводится задним числом ни из настройки `auto`, ни из чего-либо ещё;
    3. документ не утверждает, КАК считалось, для модели, обученной прежней
       версией программы;
    4. клиенту объяснена разница двух отпечатков – иначе пересохранение файла
       в Excel читается как подмена данных;
    5. отпечатком не называется значение, которое отпечатком не является.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from aurora_html.sections import _render_certificate_block  # noqa: E402
from aurora_pptx.builder import строки_сертификата  # noqa: E402
from engines.methodology_cert import (  # noqa: E402
    _extract_adstock_protocol,
    _extract_data_fingerprint,
    строки_отпечатка_данных,
    строки_протокола_затухания,
)

СОДЕРЖИМОЕ = 'f4' + 'e' * 62
ФАЙЛ = '8d' + '3' * 62


def _модель_с_фактами(**переопределения):
    модель = {
        'reproducibility': {
            'seed': 42,
            'data_fingerprint': {
                'content': {
                    'status': 'ok', 'algo': 'aurora-frame-v1',
                    'content_sha256': СОДЕРЖИМОЕ, 'n_rows': 31, 'n_cols': 34,
                    'columns': ['Date', 'OLV'],
                },
                'file': {
                    'status': 'ok', 'algo': 'sha256-full-file',
                    'file_sha256': ФАЙЛ, 'size_bytes': 65894,
                    'file_name': 'данные.xlsx', 'file_ext': '.xlsx',
                },
            },
        },
        'adstock_selection': {
            'ТВ': {'requested': 'auto', 'resolved': 'geometric', 'by': 'bic'},
            'Радио': {'requested': 'weibull', 'resolved': 'weibull', 'by': 'user'},
        },
    }
    модель.update(переопределения)
    return модель


# Модель, обученная до 06.07.2026: полей нет, в настройке стоит «auto».
МОДЕЛЬ_РАННЕЙ_ВЕРСИИ = {
    'reproducibility': {},
    'channel_adstock_types': {'ТВ': 'auto', 'Радио': 'auto'},
    'config': {'adstock_config': {'ТВ': 'auto', 'Радио': 'auto'}},
}


def _сертификат(модель, статус='issued'):
    return {
        'status': статус,
        'reason': None,
        'hash': 'a' * 64,
        'certificate_version': '1.3',
        'reproducibility': {'status': 'recorded', 'seed': 42, 'seed_source': 'config'},
        'checks': {'negative_baseline': 'passed'},
        'data_fingerprint': _extract_data_fingerprint(модель),
        'adstock_protocol': _extract_adstock_protocol(модель),
    }


# ── 1. Извлечение: только записанное, ничего достроенного ───────────────────

def test_отпечаток_данных_прочитан_из_паспорта():
    отпечаток = _extract_data_fingerprint(_модель_с_фактами())
    assert отпечаток['status'] == 'recorded'
    assert отпечаток['content']['sha256'] == СОДЕРЖИМОЕ
    assert отпечаток['content']['n_rows'] == 31
    assert отпечаток['file']['sha256'] == ФАЙЛ
    assert отпечаток['file']['file_name'] == 'данные.xlsx'


def test_у_модели_ранней_версии_отпечатка_нет():
    assert _extract_data_fingerprint(МОДЕЛЬ_РАННЕЙ_ВЕРСИИ)['status'] == 'absent'
    assert _extract_data_fingerprint({})['status'] == 'absent'


def test_неснятая_половина_отпечатка_не_печатается():
    """Половины отказывают независимо: файл могли удалить до обучения."""
    модель = _модель_с_фактами()
    модель['reproducibility']['data_fingerprint']['file'] = {
        'status': 'unavailable', 'reason': 'FileNotFoundError'}
    отпечаток = _extract_data_fingerprint(модель)
    assert отпечаток['status'] == 'partial'
    assert отпечаток['file'] is None
    assert отпечаток['content']['sha256'] == СОДЕРЖИМОЕ


def test_отпечатком_не_называется_то_что_им_не_является():
    """🔴 Усечённое или подставленное значение под словом «отпечаток» читателю
    неотличимо от настоящего, а сверить его он не сможет."""
    for мусор in ('', 'нет', 'f4ee', 'z' * 64, None, 12345):
        модель = _модель_с_фактами()
        модель['reproducibility']['data_fingerprint']['content']['content_sha256'] = мусор
        отпечаток = _extract_data_fingerprint(модель)
        assert (отпечаток.get('content') is None), мусор


def test_протокол_переноса_прочитан_из_записи_обучения():
    протокол = _extract_adstock_protocol(_модель_с_фактами())
    assert протокол['status'] == 'recorded'
    каналы = {канал['name']: канал for канал in протокол['channels']}
    assert каналы['ТВ'] == {'name': 'ТВ', 'requested': 'auto',
                            'resolved': 'geometric', 'by': 'bic'}
    assert каналы['Радио']['by'] == 'user'


def test_тип_переноса_не_выводится_из_настройки_auto():
    """🔴 Класс дефекта, который в этом продукте выкорчёвывали трижды.

    У модели ранней версии `channel_adstock_types` = 'auto' – это настройка
    «выбери сам», а не тип. Достроить из неё «geometric» значит утверждать в
    заверяемом документе то, чего в модели не записано.
    """
    протокол = _extract_adstock_protocol(МОДЕЛЬ_РАННЕЙ_ВЕРСИИ)
    assert протокол == {'status': 'absent', 'channels': []}


def test_тип_переноса_не_берётся_даже_из_явной_настройки():
    """Настройка «geometric» в старой модели – всё ещё настройка, а не запись о
    применении: заверять по ней означало бы утверждать, КАК считалось, опираясь
    на сегодняшний код, тогда как модель обучена прежней версией программы."""
    протокол = _extract_adstock_protocol({
        'channel_adstock_types': {'ТВ': 'geometric'},
        'config': {'adstock_config': {'ТВ': 'geometric'}},
    })
    assert протокол['status'] == 'absent'


def test_незнакомый_тип_в_протоколе_не_печатается():
    протокол = _extract_adstock_protocol({'adstock_selection': {
        'ТВ': {'requested': 'auto', 'resolved': 'auto', 'by': 'bic'},
        'Радио': {'requested': 'auto', 'resolved': 'сверхновый', 'by': 'bic'},
    }})
    assert протокол['status'] == 'absent'


# ── 2. Отчёт: факты и оговорки ──────────────────────────────────────────────

def test_отчёт_печатает_оба_отпечатка_целиком():
    вывод = _render_certificate_block({'certificate': _сертификат(_модель_с_фактами())})
    assert 'Исходные данные' in вывод
    assert СОДЕРЖИМОЕ in вывод, 'отпечаток содержимого не напечатан целиком'
    assert ФАЙЛ in вывод, 'отпечаток файла не напечатан целиком'
    assert 'строк: 31, столбцов: 34' in вывод
    assert 'данные.xlsx' in вывод
    assert '65 894 байт' in вывод


def test_отчёт_объясняет_разницу_двух_отпечатков():
    """🔴 Без этой оговорки первый же клиент, пересохранивший таблицу в Excel,
    прочитает расхождение по файлу как подмену данных."""
    вывод = _render_certificate_block({'certificate': _сертификат(_модель_с_фактами())})
    assert 'не меняется, если вы просто откроете файл и пересохраните его' in вывод
    assert 'означает другой файл, а не другие данные' in вывод


def test_отчёт_различает_отпечаток_данных_и_отпечаток_расчёта():
    """В том же блоке выше сказано, что отпечаток расчёта покрывает файл модели
    и исходные данные в него не входят. Без явного разграничения два соседних
    утверждения читаются как противоречие."""
    вывод = _render_certificate_block({'certificate': _сертификат(_модель_с_фактами())})
    assert 'Это отдельный отпечаток' in вывод
    assert 'покрывает файл модели, а этот – данные' in вывод


def test_отчёт_показывает_по_каналу_что_просили_и_кто_выбрал():
    вывод = _render_certificate_block({'certificate': _сертификат(_модель_с_фактами())})
    assert 'Перенос эффекта по каналам' in вывод
    assert 'запрошен автоматический подбор' in вывод
    assert 'применён геометрический' in вывод
    assert 'подобран программой по критерию BIC' in вывод
    assert 'задан вами в настройках' in вывод, 'канал с явной настройкой'
    assert 'применён вейбулловский' in вывод


def test_отчёт_называет_выгрузку_параметров_но_не_печатает_их():
    """Решение владельца 16.08: полное раскрытие параметров – по отдельному
    действию пользователя, а не в каждом отчёте."""
    вывод = _render_certificate_block({'certificate': _сертификат(_модель_с_фактами())})
    assert 'выгружается отдельно' in вывод
    for параметр in ('beta_mean', 'alpha', 'gamma', 'decay', 'hdi_'):
        assert параметр not in вывод, f'параметр канала уехал в сертификат: {параметр}'


# ── 3. Модель ранней версии: честный статус вместо подстановки ──────────────

def test_отчёт_честно_говорит_что_фактов_нет():
    вывод = _render_certificate_block({'certificate': _сертификат(
        МОДЕЛЬ_РАННЕЙ_ВЕРСИИ, статус='not_attested')})
    assert 'Отпечаток исходных данных не записан' in вывод
    assert 'Тип переноса эффекта при обучении не зафиксирован' in вывод
    assert 'Переобучите модель' in вывод


def test_отчёт_не_утверждает_как_считалось_у_старой_модели():
    """🔴 Соблазнительная фраза «расчёт шёл по геометрическому переносу»
    опирается на сегодняшний код, а модель обучена прежней версией программы,
    поведение которой этот документ не заверяет."""
    вывод = _render_certificate_block({'certificate': _сертификат(
        МОДЕЛЬ_РАННЕЙ_ВЕРСИИ, статус='not_attested')})
    # «применён <тип>» запрещено; «применённое значение» в честной формулировке
    # о том, чего в модели нет, – законно, поэтому проверяем с пробелом.
    for запрещено in ('геометрическ', 'вейбулловск', 'расчёт шёл', 'применён '):
        assert запрещено not in вывод, запрещено


def test_на_отказе_разделов_нет():
    """При статусе `unavailable` заверять нечего: раздел о данных рядом со
    словами «заверение недоступно» только запутает."""
    вывод = _render_certificate_block({'certificate': {
        'status': 'unavailable', 'reason': 'Заверять нечего.', 'hash': None,
        'reproducibility': {'status': 'absent'},
        'checks': {'negative_baseline': 'absent'},
        'data_fingerprint': _extract_data_fingerprint(_модель_с_фактами()),
        'adstock_protocol': _extract_adstock_protocol(_модель_с_фактами()),
    }})
    assert 'Исходные данные' not in вывод
    assert СОДЕРЖИМОЕ not in вывод
    assert '<ul' not in вывод


# ── 4. Паритет отчёта и презентации ─────────────────────────────────────────

def test_слайд_получает_те_же_факты_в_краткой_форме():
    строки = dict(строки_сертификата(_сертификат(_модель_с_фактами())))
    assert строки['Отпечаток данных (содержимое)'] == f'{СОДЕРЖИМОЕ[:12]}…'
    assert строки['Перенос эффекта'] == 'по каналам различается'


def test_слайд_не_молчит_о_том_о_чём_говорит_отчёт():
    """🔴 Отчёт для модели ранней версии прямо говорит, что фактов нет. Слайд,
    который в этом случае просто не показывает строк, оставляет читателя с
    впечатлением, что показывать было нечего."""
    строки = dict(строки_сертификата(_сертификат(
        МОДЕЛЬ_РАННЕЙ_ВЕРСИИ, статус='not_attested')))
    assert строки['Отпечаток данных'] == 'не записан'
    assert строки['Перенос эффекта'] == 'не зафиксирован'


def test_слайд_не_показывает_отпечаток_файла_без_оговорки():
    """В узкой колонке слайда оговорке о двух отпечатках места нет, поэтому
    отпечаток файла там не показывается вовсе: показать его рядом без
    объяснения значит подтолкнуть клиента к выводу о подмене данных."""
    строки = dict(строки_сертификата(_сертификат(_модель_с_фактами())))
    assert ФАЙЛ[:12] not in ''.join(строки.values())


def test_единый_перенос_назван_на_слайде_прямо():
    cert = _сертификат({'adstock_selection': {
        'ТВ': {'requested': 'auto', 'resolved': 'geometric', 'by': 'bic'},
        'Радио': {'requested': 'auto', 'resolved': 'geometric', 'by': 'bic'},
    }})
    строки = dict(строки_сертификата(cert))
    assert строки['Перенос эффекта'] == 'геометрический (подобран программой)'


def test_состояния_совпадают_в_обоих_форматах():
    """Факт есть в отчёте – значит есть и на слайде, и наоборот."""
    for модель, статус in ((_модель_с_фактами(), 'issued'),
                           (МОДЕЛЬ_РАННЕЙ_ВЕРСИИ, 'not_attested')):
        cert = _сертификат(модель, статус=статус)
        отчёт_данные = bool(строки_отпечатка_данных(cert, полностью=True))
        отчёт_перенос = bool(строки_протокола_затухания(cert, подробно=True))
        слайд = dict(строки_сертификата(cert))
        assert отчёт_данные == ('Отпечаток данных (содержимое)' in слайд)
        assert отчёт_перенос == (слайд.get('Перенос эффекта') != 'не зафиксирован')


# ── 5. Клиентский текст ─────────────────────────────────────────────────────

def test_длинного_тире_в_новых_строках_нет():
    for модель, статус in ((_модель_с_фактами(), 'issued'),
                           (МОДЕЛЬ_РАННЕЙ_ВЕРСИИ, 'not_attested')):
        вывод = _render_certificate_block({'certificate': _сертификат(модель, статус)})
        assert '—' not in вывод
        слайд = строки_сертификата(_сертификат(модель, статус))
        assert all('—' not in f'{метка}{значение}' for метка, значение in слайд)
