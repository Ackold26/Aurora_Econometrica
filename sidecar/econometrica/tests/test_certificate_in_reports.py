def test_клиенту_не_уходит_длинное_тире():
    """🔴 Ф-05, переписан после третьего аудита (Low).

    Прежняя версия проверяла ровно ОДНУ причину отказа из восьми: вызов с пустым
    манифестом всегда падает на «Манифест недоступен», до остальных веток дело
    не доходило, и `причины[0] if причины else 'причина'` делал тест
    нечувствительным даже к исчезновению исключения. Проверяем следствие: ни в
    одной клиентской строке обоих модулей нет длинного тире.
    """
    import re
    from pathlib import Path as _Path

    for модуль in ('engines/methodology_cert.py', 'aurora_html/sections.py'):
        путь = _Path(__file__).parent.parent / модуль
        нарушения = []
        for n, строка in enumerate(путь.read_text(encoding='utf-8').splitlines(), 1):
            if '—' not in строка:
                continue
            голая = строка.strip()
            # Комментарии и докстроки — не клиентский текст.
            if голая.startswith('#') or голая.startswith('"""') or голая.startswith('*'):
                continue
            if re.match(r"^\s*(f?')", строка) or re.search(r"=\s*f?'", строка):
                нарушения.append(f'{модуль}:{n}: {голая[:70]}')
        assert not нарушения, 'длинное тире в клиентских строках:\n' + '\n'.join(нарушения)

    # И в самом отрендеренном блоке — тоже.
    вывод = _render_certificate_block({'certificate': _сертификат()})
    assert '—' not in вывод


def test_слайд_методологии_действительно_зовёт_строки_сертификата():
    """🔴 Ф-04, переписан после третьего аудита (Low).

    Прежняя версия искала подстроку в исходнике — её удовлетворял и
    закомментированный вызов, то есть ровно то, как выглядит откат правки.
    Проверяем следствие: вызов исполняемый, не в комментарии.
    """
    import ast
    import inspect
    from aurora_pptx.builder import AuroraPPTXBuilder

    import textwrap
    исходник = textwrap.dedent(inspect.getsource(AuroraPPTXBuilder.s10_methodology))
    дерево = ast.parse(исходник)
    зовут = {
        узел.func.id
        for узел in ast.walk(дерево)
        if isinstance(узел, ast.Call) and isinstance(узел.func, ast.Name)
    }
    assert 'строки_сертификата' in зовут, (
        'слайд методологии не вызывает строки сертификата (упоминание в '
        'комментарии не считается) — блок молча исчезнет из презентации'
    )



def test_пороги_вероятности_в_тексте_совпадают_с_движком():
    """🔴 Третий аудит, Low: числа 20 % и 80 % продублированы словами в
    клиентском тексте, а живут в движке (`PROB_OK` / `PROB_FAIL`). Сегодня
    формулировки верны, но сторожа на связь не было: сдвиг порога в движке
    молча разошёлся бы с тем, что читает клиент.
    """
    from utils.negative_baseline import PROB_OK, PROB_FAIL
    from aurora_html.sections import _ПРОВЕРКА_БАЗЫ

    ок = str(int(PROB_OK * 100))
    провал = str(int(PROB_FAIL * 100))
    assert ок in _ПРОВЕРКА_БАЗЫ['passed'], (
        f'текст «пройдено» не называет порог {ок} % из движка')
    assert ок in _ПРОВЕРКА_БАЗЫ['watch'] and провал in _ПРОВЕРКА_БАЗЫ['watch'], (
        f'текст «наблюдать» не называет границы {ок}–{провал} % из движка')
    assert провал in _ПРОВЕРКА_БАЗЫ['failed'], (
        f'текст «провал» не называет порог {провал} % из движка')


def test_повторяемость_обещана_только_там_где_она_есть():
    """🔴 Третий аудит, High: подвал безусловно обещал «при повторном обучении
    числа сохранятся», а печатался по одному лишь наличию отпечатка. Отпечаток
    выдаётся и при `not_attested`, где паспорт ОТСУТСТВУЕТ — то есть зерно не
    записано и повторить прогон побитово нельзя. Клиент читал обещание,
    переобучал и получал другую разбивку.
    """
    без_паспорта = _render_certificate_block({'certificate': _сертификат(
        status='not_attested', reproducibility={'status': 'absent'},
        reason='зерно не записано')})
    assert 'числа сохранятся' not in без_паспорта, (
        'обещана повторяемость модели, у которой параметры прогона не записаны'
    )
    assert 'может дать другие числа' in без_паспорта

    с_паспортом = _render_certificate_block({'certificate': _сертификат()})
    assert 'числа сохранятся' in с_паспортом

    детерминированный = _render_certificate_block({'certificate': _сертификат(
        status='issued', reproducibility={'status': 'deterministic'})})
    assert 'числа сохранятся' in детерминированный
