"""Движок обязан ОТДАВАТЬ признак отключённых порогов окупаемости.

Инцидент, ради которого заведён (2026-08-02): признак `money_roi_unavailable`
жил только внутри Python — его считал `decomposer` и передавал в
`channel_action`, где абсолютные breakeven-пороги (шаги 4, 6, 7, 8) не
применяются. Во фронт он не выходил, и экран показывал вердикты как обычно:
пользователь не мог знать, что сравнения с точкой безубыточности за ними нет.

Вычислять то же самое на фронте нельзя — это второй источник истины, он
разойдётся (так ломались ярусы MQS: слой представления держал свою копию
порогов). Поэтому поле обязано присутствовать в ответе decompose.

Проверка идёт по исходнику: полный `decompose_contributions` требует обученной
модели, а защитить надо ровно от удаления ключа из ответа. Тот же приём, что у
`test_mqs_tier_rust_single_source` для Rust-зеркала.
"""
import os
import re

_HERE = os.path.dirname(os.path.abspath(__file__))
_DECOMPOSER = os.path.join(os.path.dirname(_HERE), "engines", "decomposer.py")


def _source():
    assert os.path.isfile(_DECOMPOSER), (
        f"Не найден {_DECOMPOSER} — путь сместился, почини тест, не отключай"
    )
    with open(_DECOMPOSER, encoding="utf-8") as f:
        return f.read()


def test_result_carries_breakeven_flag():
    """Ключ есть в ответе decompose."""
    assert "'money_roi_unavailable':" in _source(), (
        "Признак отключённых порогов пропал из ответа decompose — экран снова "
        "будет молчать о том, что вердикты не сравниваются с безубыточностью"
    )


def test_flag_is_computed_not_hardcoded():
    """Значение выводится из состояния расчёта, а не прибито константой.

    Прибитый False вернул бы молчание, прибитый True — ложное предупреждение на
    исправных проектах; и то и другое зелёно проходит проверку «ключ есть».
    """
    src = _source()
    m = re.search(r"'money_roi_unavailable':\s*(.{0,200})", src, re.DOTALL)
    assert m, "ключ найден, но значение не разобрать"
    value = m.group(1)
    assert "_insight_money_roi_na" in value, (
        "признак больше не опирается на посчитанный флаг — проверьте, не прибит "
        f"ли он константой: {value[:120]!r}"
    )
    assert not re.match(r"\s*(True|False)\s*,", value), (
        "признак прибит константой — он обязан отражать реальное состояние расчёта"
    )


def test_нулевая_ценность_единицы_отключает_пороги():
    """Граница «ценность единицы задана» совпадает с фронтовой (2026-08-03).

    Развилка задачи 0 звучала так: фронт считает базу ROI по `vpcu > 0`, движок —
    по `kpi_unit_cost is None`, поэтому при введённом нуле движок якобы пороги
    ПРИМЕНЯЕТ, а экран говорит «база не определена». Замер обеих сторон показал,
    что это не так: движок берёт значение только строго положительным (и override
    из запроса, и снимок из pickle), при нуле кладёт None и уходит в
    `money_roi_unavailable`. Границы совпадают — чинить нечего.

    Но стерёг эту границу только фронт (`tier2-roi-base.guard.test.js`), а живёт
    она в движке в ДВУХ местах. Разъедься они молча — вернулся бы ровно тот
    дефект, который сняли внешним аудитом: экран говорит «база не определена»,
    а вердикты за ним считаются по абсолютным порогам.
    """
    src = _source()
    # Оба места, где значение принимается: override из запроса и снимок из pickle.
    assert re.search(
        r"kpi_unit_cost_override is not None and float\(kpi_unit_cost_override\) > 0",
        src,
    ), "граница override перестала быть строго положительной — ноль начнёт включать пороги"
    assert re.search(
        r"float\(_snap\) if _snap is not None and float\(_snap\) > 0 else None",
        src,
    ), "граница снимка перестала быть строго положительной — старые проекты разойдутся с экраном"


def test_effectiveness_mode_counted_as_no_breakeven():
    """Режим эффективности тоже означает отсутствие денежных порогов.

    Докстринг `channel_action` обещает, что этот случай приходит тем же
    признаком, — фактически вызывающий передаёт только счётный-без-стоимости.
    В ответе оба случая сведены сознательно: для пользователя разницы нет.
    """
    src = _source()
    m = re.search(r"'money_roi_unavailable':\s*(.{0,200})", src, re.DOTALL)
    assert m and "effectiveness" in m.group(1), (
        "режим эффективности выпал из признака — в нём абсолютных денежных "
        "порогов тоже нет, а экран об этом промолчит"
    )
