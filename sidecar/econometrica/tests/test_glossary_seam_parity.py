"""Сторож паритета шва «глоссарий XLSX»: фронт передаёт — Rust принимает.

Зачем нужен (найдено собственным аудитом 2026-08-04). Глоссарий листа
«Глоссарий» в многолистовом XLSX собирается из ЕДИНОГО источника
`src/lib/glossary.js` (50 терминов): фронт читает его через `getAllTerms()` и
передаёт параметром `glossary` в команду `econ_export_xlsx`, а Rust пассивно
пишет переданное. Если параметр не пришёл, Rust падает на запасной путь —
11 зашитых терминов.

🔴 Дыра, ради которой написан этот сторож: покрытие было ОДНОСТОРОННИМ.
Rust-тест `glossary_xlsx_uses_frontend_terms_when_provided` вызывает
`build_xlsx` напрямую с уже готовым списком — про фронт он не знает ничего.
Фронтовых тестов на `econ_export_xlsx`/`exportXlsx` не существует вовсе.
Значит удаление ОДНОЙ строки в `ReportStep.svelte` оставляло весь набор
зелёным, а клиент молча получал 11 терминов вместо 50: запасной путь на то и
запасной, что не отличается от штатного ничем видимым.

Это тот же класс, что «границу стерегла только одна сторона» — сторож обязан
стоять на ОБОИХ концах шва, иначе он декоративен ровно наполовину.

Область поиска — только код продукта. В Rust-файле тело `#[cfg(test)]`
отрезается: образцы, которые ищет сторож, есть и в тексте тестов, и без
обрезки сторож находил бы САМ СЕБЯ и оставался зелёным при полностью
обезвреженном коде (в этой линии ловушка срабатывала дважды).
"""

from __future__ import annotations

from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[3]
_FRONT = _ROOT / "src" / "lib" / "components" / "pipeline" / "ReportStep.svelte"
_RUST = _ROOT / "src-tauri" / "src" / "commands" / "report.rs"
_GLOSSARY_JS = _ROOT / "src" / "lib" / "glossary.js"


def _rust_product_code() -> str:
    """Исходник Rust БЕЗ тестового модуля.

    Обрезаем по `#[cfg(test)]`: иначе сторож находит собственные образцы в
    тексте Rust-тестов и остаётся зелёным при вырезанном продакшн-коде.
    """
    src = _RUST.read_text(encoding="utf-8")
    marker = src.find("#[cfg(test)]")
    return src if marker == -1 else src[:marker]


def _call_window(src: str, command: str, lines_after: int = 25) -> str:
    """Окно ПО СТРОКАМ вокруг НАСТОЯЩЕГО вызова команды.

    🔴 Два условия, и оба выстраданы:
    1. Окно берётся по строкам, не байтовым срезом: в файле кириллица, и
       `src[at:at+900]` разрубает многобайтовый символ (в этой линии такое уже
       роняло сторож паникой).
    2. Ищется строка, где рядом с именем команды стоит `invoke(` — иначе
       находится ПЕРВОЕ упоминание, а это комментарий в шапке файла
       («R3: econ_export_xlsx → multi-sheet XLSX»). Первая редакция сторожа
       на этом и споткнулась: окно бралось вокруг комментария и не содержало
       ничего из вызова. Тот же класс, что «сторож принял закомментированный
       вызов за живой».
    """
    lines = src.splitlines()
    for i, line in enumerate(lines):
        if command in line and "invoke(" in line:
            return "\n".join(lines[i : i + lines_after])
    return ""


@pytest.mark.skipif(not _FRONT.exists(), reason="фронт-компонент не найден")
def test_front_passes_glossary_to_xlsx_command() -> None:
    """Фронт обязан читать единый источник и передавать его ИМЕННО в эту команду.

    🔴 Проверяем связку внутри вызова, а не наличие слов в файле. Первая
    редакция этого сторожа искала `"glossary" in src` — и не краснела на
    мутации, потому что слово живёт ещё и в импорте `$lib/glossary.js`.
    Сторож, написанный вместе с починкой, унаследовал её слепоту; поймано
    мутацией сразу после написания.
    """
    src = _FRONT.read_text(encoding="utf-8")

    assert "getAllTerms" in src, (
        "ReportStep.svelte больше не читает единый источник глоссария: импорт "
        "getAllTerms пропал. Клиент получит запасные 11 терминов вместо 50, и "
        "ни один другой тест этого не заметит."
    )

    window = _call_window(src, "econ_export_xlsx")
    assert window, (
        "ReportStep.svelte не вызывает econ_export_xlsx — шов оборван на "
        "фронтовом конце."
    )
    assert "glossary" in window, (
        "в вызове econ_export_xlsx пропало поле glossary: команда уходит без "
        "терминов, Rust молча падает на запасные 11 вместо 50."
    )
    assert "getAllTerms" in window, (
        "поле glossary в вызове есть, но заполняется НЕ из единого источника "
        "(getAllTerms в окне вызова не найден) — значит список снова живёт "
        "второй копией, ровно то, что этот шов и устраняет."
    )


def test_rust_accepts_glossary_parameter() -> None:
    """Rust-конец шва обязан принимать параметр и доносить его до сборки листа."""
    code = _rust_product_code()

    assert "glossary: Option<Value>" in code, (
        "команда econ_export_xlsx больше не принимает параметр glossary — "
        "передавать термины с фронта физически некуда."
    )
    assert "glossary: Option<&Value>" in code, (
        "build_xlsx больше не принимает glossary: параметр принят командой, но "
        "до сборки листа не доходит."
    )


def test_rust_keeps_builtin_fallback() -> None:
    """Запасной путь обязан остаться: старые вызовы без поля должны работать.

    Обратная сторона того же шва. Если запасные термины вырезать «за
    ненадобностью», любой вызов без glossary даст пустой лист вместо
    сокращённого, и это будет хуже нынешнего поведения.
    """
    code = _rust_product_code()
    assert '"MQS"' in code and '"Adstock"' in code, (
        "из report.rs пропал запасной список терминов: вызов без параметра "
        "glossary даст пустой лист «Глоссарий» вместо сокращённого."
    )


def test_single_source_has_more_terms_than_fallback() -> None:
    """Смысл шва: единый источник заметно богаче запасного списка.

    Если источник усохнет до размера запасного, весь механизм передачи теряет
    смысл, и это сигнал о поломке генератора глоссария, а не о норме.
    """
    js = _GLOSSARY_JS.read_text(encoding="utf-8")
    terms = js.count("\n  term: ") or js.count("term:")
    # 🔴 Порог поднят с 20 до 40 по находке аудита: при заявленных 50 терминах
    # порог 20 пропускал поломку генератора, отдающую половину корпуса, — клиент
    # получал бы неполный лист «Глоссарий» при зелёном стороже.
    assert terms >= 40, (
        f"единый источник глоссария содержит подозрительно мало терминов "
        f"({terms}): передавать его на замену запасным 11 незачем — проверьте "
        f"tools/build_glossary.py и docs/GLOSSARY_v2_1_0.md."
    )
