"""Критерий совпадения двух расчётов: допуск, режимы и отказ от сверки.

Стережём следствия, ради которых критерий и заводился:

    1. с тем же зерном и в той же среде допуск НУЛЕВОЙ – иначе обещание
       «повторите и получите то же» подменяется обещанием «получите похожее»;
    2. режим определяется по паспортам, а не выбирается стороной спора;
    3. сокращённый расчёт получает более широкий допуск честно и явно, а не
       проходит по строгому;
    4. заведомо разные расчёты объявляются несовпавшими – критерий, который
       всегда говорит «совпало», не критерий;
    5. расчёты по разным данным, показателям или наборам каналов не сверяются
       вовсе: это не «несовпадение», а несравнимость;
    6. величина, которую не удалось сверить, объявляется несверявшейся, а не
       совпавшей;
    7. числа в клиентской формулировке критерия те же, что применяет проверка.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from utils import repro_tolerance as rt  # noqa: E402

ОТПЕЧАТОК = 'a1' + 'b' * 62

КАНАЛЫ = ('Телевидение', 'Интернет')


def _паспорт(*, seed=42, draws=2000, chains=4, pymc='5.28.4', platform='win-1'):
    return {
        'seed': seed,
        'sampler_tier': 'numpyro-nuts',
        'platform': platform,
        'has_compiler': True,
        'mcmc': {'chains': chains, 'draws': draws, 'tune': 2000},
        'versions': {'python': '3.12.10', 'numpy': '2.4.2', 'pymc': pymc},
        'data_fingerprint': {'content': {'status': 'ok', 'content_sha256': ОТПЕЧАТОК}},
    }


def _канал(roi=10.0, доля=50.0, beta=0.1, decay=0.25, alpha=1.5, gamma=0.5,
           диапазон=(5.0, 15.0)):
    return {
        'roi': roi,
        'contribution_pct': доля,
        'beta': beta,
        'decay': decay,
        'alpha': alpha,
        'gamma': gamma,
        'roi_ci_low': диапазон[0],
        'roi_ci_high': диапазон[1],
    }


def _прогон(паспорт=None, каналы=None, *, разбивка=True, kpi='Продажи', медиа=КАНАЛЫ):
    return {
        'model_path': 'модель.pkl',
        'project_dir': 'проект',
        'passport': паспорт or _паспорт(),
        'config': {'kpi_column': kpi, 'media_columns': list(медиа)},
        'channels': каналы or {имя: _канал() for имя in КАНАЛЫ},
        'decomposition_available': разбивка,
        'decomposition_reason': None if разбивка else 'файл данных не найден',
    }


@pytest.fixture
def сверка(monkeypatch):
    """Подменяет чтение расчётов: тесты о критерии, а не об обучении модели."""
    def _сверить(прогон_а, прогон_б, **kwargs):
        очередь = [прогон_а, прогон_б]
        monkeypatch.setattr(rt, 'read_run', lambda *_a, **_k: очередь.pop(0))
        return rt.compare_runs('а.pkl', 'б.pkl', **kwargs)
    return _сверить


# ── 1. Тот же режим, нулевой допуск ──────────────────────────────────────────

def test_то_же_зерно_и_среда_дают_точное_совпадение(сверка):
    итог = сверка(_прогон(), _прогон())
    assert итог['status'] == 'compared'
    assert итог['mode'] == rt.MODE_EXACT
    assert итог['verdict'] == 'match'
    assert set(итог['tolerances'].values()) == {0.0}


def test_при_том_же_зерне_даже_полпроцента_это_несовпадение(сверка):
    """Допуск нулевой не на словах: побитовое равенство измерено, значит любое
    расхождение при том же зерне означает различие где-то ещё."""
    сдвинутые = {имя: _канал() for имя in КАНАЛЫ}
    сдвинутые['Интернет']['roi'] = 10.05  # +0,5 %
    итог = сверка(_прогон(), _прогон(каналы=сдвинутые))
    assert итог['mode'] == rt.MODE_EXACT
    assert итог['verdict'] == 'mismatch'
    испорченный = [c for c in итог['channels'] if c['channel'] == 'Интернет'][0]
    assert испорченный['quantities']['roi']['within'] is False


def test_широкий_правдоподобный_диапазон_не_прощает_нулевой_допуск(сверка):
    """Вторая опора критерия работает только там, где допуск ненулевой: иначе
    она обесценила бы обещание точного повтора."""
    сдвинутые = {имя: _канал() for имя in КАНАЛЫ}
    сдвинутые['Телевидение']['roi'] = 10.2  # 2 % значения, но 2 % ширины диапазона
    итог = сверка(_прогон(), _прогон(каналы=сдвинутые))
    assert итог['verdict'] == 'mismatch'


# ── 2. Другое зерно при полном расчёте ───────────────────────────────────────

def test_другое_зерно_полный_расчёт_попадает_в_строгий_допуск(сверка):
    итог = сверка(_прогон(), _прогон(_паспорт(seed=7)))
    assert итог['mode'] == rt.MODE_STRICT
    assert итог['tolerances']['roi'] == 5.0


def test_расхождение_в_пределах_допуска_это_совпадение(сверка):
    сдвинутые = {имя: _канал() for имя in КАНАЛЫ}
    сдвинутые['Телевидение']['roi'] = 10.4      # +4 %
    сдвинутые['Телевидение']['contribution_pct'] = 51.0  # +1,0 п.п.
    итог = сверка(_прогон(), _прогон(_паспорт(seed=7), сдвинутые))
    assert итог['verdict'] == 'match'


def test_расхождение_сверх_допуска_это_несовпадение(сверка):
    сдвинутые = {имя: _канал() for имя in КАНАЛЫ}
    сдвинутые['Телевидение']['beta'] = 0.13  # +30 %
    итог = сверка(_прогон(), _прогон(_паспорт(seed=7), сдвинутые))
    assert итог['verdict'] == 'mismatch'
    плохой = [c for c in итог['channels'] if c['channel'] == 'Телевидение'][0]
    assert плохой['quantities']['beta']['within'] is False
    assert плохой['quantities']['beta']['deviation'] == pytest.approx(30.0, abs=0.01)


def test_доля_вклада_считается_в_пунктах_а_не_в_процентах(сверка):
    """Доля – сама процент; сравнивать её относительно значит наказывать мелкий
    канал за то, что он мелкий."""
    сдвинутые = {имя: _канал() for имя in КАНАЛЫ}
    сдвинутые['Интернет']['contribution_pct'] = 51.4  # +1,4 п.п. = +2,8 %
    итог = сверка(_прогон(), _прогон(_паспорт(seed=7), сдвинутые))
    канал = [c for c in итог['channels'] if c['channel'] == 'Интернет'][0]
    величина = канал['quantities']['contribution_pct']
    assert величина['unit'] == 'п.п.'
    assert величина['deviation'] == pytest.approx(1.4, abs=0.001)
    assert величина['within'] is True


# ── 3. Вторая опора: доля правдоподобного диапазона ──────────────────────────

def test_расхождение_внутри_четверти_диапазона_засчитывается(сверка):
    """Канал с широким разбросом: 8 % значения, но лишь 8 % ширины диапазона –
    вывода такое смещение не меняет."""
    сдвинутые = {имя: _канал() for имя in КАНАЛЫ}
    сдвинутые['Телевидение']['roi'] = 10.8  # +8 % при допуске 5 %
    итог = сверка(_прогон(), _прогон(_паспорт(seed=7), сдвинутые))
    канал = [c for c in итог['channels'] if c['channel'] == 'Телевидение'][0]
    величина = канал['quantities']['roi']
    assert величина['within'] is True
    assert величина['passed_by'] == 'диапазон'
    assert итог['verdict'] == 'match'


def test_узкий_диапазон_не_спасает_крупное_расхождение(сверка):
    узкие = {имя: _канал(диапазон=(9.9, 10.1)) for имя in КАНАЛЫ}
    сдвинутые = {имя: _канал(диапазон=(9.9, 10.1)) for имя in КАНАЛЫ}
    сдвинутые['Телевидение']['roi'] = 10.8
    итог = сверка(_прогон(каналы=узкие), _прогон(_паспорт(seed=7), сдвинутые))
    assert итог['verdict'] == 'mismatch'


