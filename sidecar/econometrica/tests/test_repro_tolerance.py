def test_ветвь_печатается_клиенту_и_различается_по_полноте_расчёта():
    сокращённый = _extract_repro_tolerance(
        {'status': 'recorded', 'mcmc': {'chains': 2, 'draws': 300, 'tune': 2000}})
    полный = _extract_repro_tolerance(
        {'status': 'recorded', 'mcmc': {'chains': 4, 'draws': 2000, 'tune': 2000}})

    assert сокращённый['applicable']['mode'] == rt.MODE_WIDE
    assert сокращённый['applicable']['total_draws'] == 600
    assert полный['applicable']['mode'] == rt.MODE_STRICT
    assert полный['applicable']['total_draws'] == 8000

    строка_а = dict(строки_критерия_совпадения(
        {'repro_tolerance': сокращённый}, подробно=True))['Ветвь, применимая к этому расчёту']
    строка_б = dict(строки_критерия_совпадения(
        {'repro_tolerance': полный}, подробно=True))['Ветвь, применимая к этому расчёту']
    assert строка_а != строка_б
    assert 'сокращённый' in строка_а and f'{rt.TOLERANCES[rt.MODE_WIDE]["roi"]:.0f} %' in строка_а
    assert 'полный' in строка_б and f'{rt.TOLERANCES[rt.MODE_STRICT]["roi"]:.0f} %' in строка_б


