# ── 6. Несверенное не выдаётся за совпавшее ──────────────────────────────────

def test_без_разбивки_окупаемость_и_вклад_объявляются_несверявшимися(сверка):
    итог = сверка(_прогон(разбивка=False), _прогон(разбивка=False))
    assert set(итог['unverified']) == set(rt.QUANTITIES_FROM_DECOMPOSITION)
    assert any('не сверялись' in примечание for примечание in итог['notes'])
    for канал in итог['channels']:
        assert 'roi' not in канал['quantities']
        assert 'beta' in канал['quantities']


def test_нулевое_базовое_значение_не_засчитывается_как_совпадение():
    assert rt.deviation(0.0, 0.0, 'relative') is None
    assert rt.deviation(None, 1.0, 'relative') is None
    assert rt.deviation(50.0, 51.4, 'points') == pytest.approx(1.4, abs=0.001)


# ── 7. Клиентская формулировка и проверка не расходятся ──────────────────────

def test_числа_в_формулировке_совпадают_с_применяемыми():
    строки = dict(rt.criterion_lines())
    строгий = rt.TOLERANCES[rt.MODE_STRICT]
    широкий = rt.TOLERANCES[rt.MODE_WIDE]
    assert f'{строгий["roi"]:.0f} %' in строки['Другое зерно, полный расчёт']
    assert f'{широкий["roi"]:.0f} %' in строки['Сокращённый расчёт или другая среда']
    assert f'{rt.CI_SHARE_LIMIT_PCT:.0f} %' in строки['Дополнительно']
    паспорт = rt.criterion_for_certificate()
    assert паспорт['other_seed_full']['tolerances'] == строгий
    assert паспорт['reduced_or_other_env']['tolerances'] == широкий
    assert паспорт['full_run_draws'] == rt.FULL_RUN_DRAWS


def test_в_клиентском_тексте_нет_длинного_тире():
    текст = ' '.join(f'{имя} {значение}' for имя, значение in rt.criterion_lines())
    текст += ' ' + rt.criterion_note()
    # Литерал записан кодом намеренно: сам файл проходит правку тире, и живое
    # длинное тире в проверке заменилось бы вместе с текстом, обессмыслив её.
    assert chr(0x2014) not in текст


def test_версия_критерия_объявлена_в_заключении(сверка):
    итог = сверка(_прогон(), _прогон())
    assert итог['criterion_version'] == rt.CRITERION_VERSION


# ── 8. Критерий доезжает в сертификат методологии ────────────────────────────

from engines.methodology_cert import (  # noqa: E402
    _extract_repro_tolerance,
    пояснение_критерия_совпадения,
    строки_критерия_совпадения,
)


def test_в_сертификате_критерий_объявлен_с_теми_же_числами():
    критерий = _extract_repro_tolerance({'status': 'recorded'})
    assert критерий['status'] == 'declared'
    assert критерий['other_seed_full']['tolerances'] == rt.TOLERANCES[rt.MODE_STRICT]
    строки = dict(строки_критерия_совпадения({'repro_tolerance': критерий}, подробно=True))
    assert 'То же зерно, та же среда' in строки
    assert 'Другое зерно, полный расчёт' in строки


def test_слайдовая_форма_короче_отчётной_и_не_молчит():
    критерий = _extract_repro_tolerance({'status': 'recorded'})
    слайд = строки_критерия_совпадения({'repro_tolerance': критерий}, подробно=False)
    отчёт = строки_критерия_совпадения({'repro_tolerance': критерий}, подробно=True)
    assert len(слайд) == 1
    assert len(отчёт) > len(слайд)
    assert слайд[0][1]


def test_режим_малых_данных_обещает_точный_повтор_а_не_допуск():
    """Закрытая формула случайной процедуры не содержит: обещать там допуск
    значило бы придумать разброс, которого нет."""
    критерий = _extract_repro_tolerance({'status': 'deterministic'})
    assert критерий['status'] == 'deterministic'
    текст = строки_критерия_совпадения({'repro_tolerance': критерий}, подробно=True)[0][1]
    assert 'те же числа' in текст
    assert '%' not in текст


def test_модель_без_паспорта_получает_честный_отказ_а_не_допуск():
    критерий = _extract_repro_tolerance({'status': 'absent'})
    assert критерий['status'] == 'absent'
    текст = строки_критерия_совпадения({'repro_tolerance': критерий}, подробно=True)[0][1]
    assert 'не применим' in текст
    assert 'Переобучите' in пояснение_критерия_совпадения({'repro_tolerance': критерий})


def test_без_раздела_в_сертификате_строк_не_печатается():
    assert строки_критерия_совпадения({}, подробно=True) == []
    assert строки_критерия_совпадения(None, подробно=False) == []
    assert пояснение_критерия_совпадения({}) == ''
