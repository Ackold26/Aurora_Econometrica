# ── 9. Замечания внешнего аналитика 2026-08-16 ───────────────────────────────
#
# Три места критерия, на которых посторонний спотыкался, восстановив модель по
# одному паспорту. Стерегутся отдельно: каждое из них молчало, а молчание
# тестами не ловится само.


def test_критерий_называет_адрес_окупаемости_и_доли_вклада():
    """Б-1: величины из критерия в паспорте отсутствуют по построению. Критерий
    обязан сказать, где они печатаются, а не оставлять проверяющего искать."""
    паспорт = rt.criterion_for_certificate()
    адрес = паспорт['quantities_from_decomposition']
    assert адрес['quantities'] == ['окупаемость канала', 'доля канала во вкладе медиа']
    assert 'Декомпозиция' in адрес['where_to_find']
    assert 'Портфель каналов' in адрес['where_to_find']
    assert 'Окупаемость каналов' in адрес['where_to_find']

    строки = dict(rt.criterion_lines())
    текст = строки['Где взять окупаемость и долю вклада']
    assert 'отчёте по модели' in текст
    # Честность важнее полноты: сверка по одному паспорту эти две величины не
    # подтверждает, и критерий говорит это прямо, а не умалчивает.
    assert 'непроверенными' in текст


def test_критерий_называет_две_величины_из_разбивки_теми_же_именами():
    """Адрес и список сверяемых величин не вправе разойтись: расхождение имён
    вернуло бы проверяющего ровно в ту неопределённость, ради которой правка."""
    паспорт = rt.criterion_for_certificate()
    for имя in паспорт['quantities_from_decomposition']['quantities']:
        assert имя in паспорт['quantities']


