-- Учёт клиентов: карточка машины плюс удержание правила В-3 проверкой в базе.
-- Решения владельца 05.09: В-1 кабинет отложен (не отменён), В-2 сущность компании не заводим,
-- В-3 только обезличенные адреса роли и метка оператора вместо имени машины – удерживать
-- ПРОВЕРКОЙ, а не соглашением (INV-38), В-4 единица подписки – машина, В-5 разметку делает
-- владелец руками.
--
-- Что эта запись изменений делает: заводит два домена-правила и одну пустую таблицу, отзывает
-- права и включает построчную защиту. Существующие таблицы НЕ ТРОГАЮТСЯ: ни одной строки в
-- licenses, activations, audit_log, device_bindings не пишется и не читается. Числа до и после
-- обязаны совпасть (46 / 241 / 12120 / 0).
--
-- Чего эта запись изменений сознательно НЕ делает:
--   * не создаёт внешнего ключа из licenses – отсутствие карточки не должно останавливать выдачу
--     лицензии; вместо ключа – проверочный запрос в приёмке;
--   * не создаёт ни триггера, ни переноса из activations.hostname – метку вписывает ТОЛЬКО
--     оператор; автоматический перенос запрещён и в будущем (см. комментарий на колонке);
--   * не создаёт ни одной политики построчной защиты – ноль политик при отозванных правах есть
--     самое закрытое состояние; политика появится вместе с кабинетом клиента (В-1), не раньше;
--   * не заводит поля «примечание» — свободного текста без назначения, у которого не бывает
--     осмысленной проверки.
--
-- 🔴 ЧЕСТНАЯ ОГОВОРКА (правка 06.09 по находке внешнего аудита А-1). Первая редакция этой шапки
-- утверждала, что миграция «не заводит свободного текстового поля — приёмника ПДн». Это было
-- неверно: колонка `company` и есть текстовое поле, и оно наполняется персональными данными не по
-- неосторожности, а НОРМАЛЬНЫМ ХОДОМ ДЕЛА — название организации у индивидуального предпринимателя
-- по закону состоит из имени человека («ИП Иванов Иван Иванович»). Проверкой это не лечится:
-- запретить такое название значит сделать поле непригодным для целого класса настоящих клиентов.
-- Ниже добавлены лишь два грубых сторожа (по образцу `operator_label`), ловящие ошибку вставки не
-- в то поле. 🔴 Само решение — принимать ли имена ИП в базу за пределами России — принимает
-- владелец; до его решения поле следует заполнять названием юридического лица, где оно есть.

-- ── 1. Домен «обезличенный адрес роли» ───────────────────────────────────────────────────────
--
-- CREATE DOMAIN не знает «if not exists», поэтому идемпотентность делается охраной по каталогу.
--
-- Проверки НАМЕРЕННО РАЗДЕЛЕНЫ на две независимые: форма и перечень. Они ловят разное, и при
-- падении видно, какая именно сработала – имя ограничения попадает в текст ошибки.
--
-- Почему проверка, а не триггер: триггер отключается одной командой и не срабатывает при
-- session_replication_role = replica; проверку нельзя ни отключить, ни обойти – её можно только
-- удалить командой определения схемы, а это видно в истории изменений. Служебная роль
-- service_role проверке подчиняется наравне со всеми.
--
-- Почему перечень внутри проверки, а не в справочной таблице: таблица правится служебным ключом
-- молча и мгновенно, проверка – только миграцией. Единственная защита этого правила – трудность
-- его ослабления.
--
-- 🔴 РАСШИРЯТЬ ПЕРЕЧЕНЬ ТОЛЬКО НОВОЙ МИГРАЦИЕЙ И ТОЛЬКО РОЛЕВЫМИ СЛОВАМИ. Внесённое сюда личное
-- имя («anton», «petrov») убивает всё правило целиком и молча.
do $mig$
begin
  if not exists (
    select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace
     where t.typname = 'role_email' and n.nspname = 'public'
  ) then
    create domain public.role_email as text
      constraint role_email_len check (length(value) between 6 and 254)
      constraint role_email_shape check (
        value ~ '^[a-z]{2,32}@[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$'
      )
      constraint role_email_local_allowed check (
        split_part(value, '@', 1) = any (array[
          'adv','analytics','aurora','buying','client','contact','digital','docs',
          'finance','hello','help','info','it','legal','licence','license','mail',
          'manager','marketing','media','mediaplan','office','order','orders',
          'partner','planner','planning','pr','purchase','reklama','research',
          'sales','smm','study','support','team','test'
        ])
      );
  end if;
end
$mig$;

comment on domain public.role_email is
  'Обезличенный адрес роли (решение владельца В-3). Две проверки: форма (только строчные латинские '
  'буквы в локальной части) и закрытый перечень ролевых слов. НЕ ловит личное имя в доменной части '
  '(planner@ivanpetrov.ru), ролевой ящик компании из одного человека и соотнесение по совокупности '
  '– обезличивание есть смягчение, а не основание (INV-38). Расширять перечень только миграцией и '
  'только ролевыми словами.';

-- ── 2. Домен «метка оператора» ───────────────────────────────────────────────────────────────
--
-- Честно о силе: проверка удерживает ФОРМУ, а не содержание. «Ноутбук Иванова» пройдёт, и никакая
-- проверка в базе этого не остановит. Ловится грубое: пустое значение, один пробел, вставленный
-- отпечаток, вставленный адрес почты, простыня.
do $mig$
begin
  if not exists (
    select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace
     where t.typname = 'operator_label' and n.nspname = 'public'
  ) then
    create domain public.operator_label as text
      constraint operator_label_len check (length(btrim(value)) between 2 and 40)
      constraint operator_label_shape check (
        value ~ '^[A-Za-zА-Яа-яЁё0-9][A-Za-zА-Яа-яЁё0-9 ()._–-]{1,39}$'
      )
      constraint operator_label_no_at check (position('@' in value) = 0)
      constraint operator_label_not_fingerprint check (value !~ '^[0-9a-fA-F]{32,}$');
  end if;
end
$mig$;

comment on domain public.operator_label is
  'Метка машины, назначенная ОПЕРАТОРОМ (решение владельца В-3). Проверяется форма, не содержание: '
  'метка с фамилией внутри пройдёт. Автоматический перенос из activations.hostname запрещён.';

-- ── 3. Карточка машины ───────────────────────────────────────────────────────────────────────
--
-- Единица – машина (В-4), поэтому ключ – отпечаток, ровно того же вида, что первичный ключ
-- device_bindings: карточка и закрепление ключа соединяются один к одному без переходников.
-- Отдельная таблица, а не колонки в licenses: на 46 лицензий приходится 12 отпечатков (до 10
-- лицензий на машину), и расхождение уже произошло – четыре отпечатка несут лицензии под разными
-- значениями customer, потому что свободный текст жил в строке лицензии и переписывался при
-- перевыдаче. Повторять эту форму для поля с ПДн нельзя.
create table if not exists public.client_machines (
  fingerprint_hash text primary key
    constraint client_machines_fp_format check (fingerprint_hash ~ '^[0-9a-f]{64}$'),

  owner_email   public.role_email,

  machine_label public.operator_label,

  -- Два грубых сторожа по образцу `operator_label` — симметрия, которой не было в первой редакции
  -- (находка аудита А-1: `company` была защищена слабее соседней колонки). Ловят ошибку вставки не
  -- в то поле, а не содержание: название с именем человека внутри пройдёт, и это осознанно.
  company text
    constraint client_machines_company_len
      check (company is null or length(btrim(company)) between 2 and 120)
    constraint client_machines_company_no_at
      check (company is null or position('@' in company) = 0)
    constraint client_machines_company_not_fingerprint
      check (company is null or company !~ '^[0-9a-fA-F]{32,}$'),

  created_at timestamptz not null default now(),

  marked_by  text not null default ''
    constraint client_machines_marked_by_len check (length(marked_by) <= 64)
);

comment on table public.client_machines is
  'Карточка машины: почта владельца, метка оператора, признак компании. Единица – машина (В-4). '
  'Заполняет оператор; функция входа об этой таблице не знает и писать в неё не должна.';
comment on column public.client_machines.fingerprint_hash is
  'Полный отпечаток машины в нижнем регистре – тот же ключ, что у device_bindings. Внешнего ключа '
  'из licenses нет намеренно: отсутствие карточки не должно останавливать выдачу лицензии.';
comment on column public.client_machines.owner_email is
  'Обезличенный адрес роли (В-3), проверяется доменом role_email. Пусто = почта не сообщена.';
comment on column public.client_machines.machine_label is
  'Вписывает ТОЛЬКО оператор. Автоматический перенос из activations.hostname запрещён решением '
  'В-3: имя машины приходит от клиента и не проверено ничем.';
comment on column public.client_machines.company is
  'Признак компании для группировки во внутреннем отчёте. Сущности компании не заводим (В-2).';
comment on column public.client_machines.marked_by is
  'Кто вписал значения. Разметку делает владелец руками (В-5), догадками не размечать.';

-- ── 4. Два рубежа, а не один ─────────────────────────────────────────────────────────────────
--
-- Ровно по образцу 20260830_device_bindings.sql: права отзываются, и построчная защита включается
-- СВЕРХ этого. Умолчания схемы public уже поправлены 05.09 (CPD-151, группа 3), но отзыв здесь
-- явный: умолчание действует только для роли, которая его задала, и полагаться на него как на
-- единственный рубеж нельзя.
--
-- Политик НЕТ ни одной, и это не упущение: ноль политик при отозванных правах есть самое закрытое
-- состояние. Разрешающая политика появится вместе с кабинетом клиента (В-1).
alter table public.client_machines enable row level security;
revoke all on public.client_machines from anon, authenticated;

-- 🔴 Служебной роли права выдаются ЯВНО. После правки умолчаний схемы 05.09 (CPD-151) новая
-- таблица прав по умолчанию не наследует, а карточку заполняет панель выдачи именно служебным
-- ключом: без этой строки таблица была бы недоступна и оператору.
grant select, insert, update, delete on public.client_machines to service_role;

-- PostgREST кеширует права: без этого проверка снаружи сразу после применения покажет СТАРОЕ
-- поведение и даст ложную зелень.
notify pgrst, 'reload schema';

