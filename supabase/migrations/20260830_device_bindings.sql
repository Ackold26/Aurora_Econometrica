-- CPD-141, шаг 1: место, куда кладётся ключ машины.
-- Применено 30.08.2026 в тихий час (последнее обращение в журнале — 29.08 20:31 UTC, сутки тишины).
--
-- Что делает шаг 1: сервер учится ПОНИМАТЬ подпись AURORA-REQ-v1. Дыра при этом не закрывается,
-- подписанных клиентов ещё нет, ни одно сегодняшнее обращение не задето. Таблица создаётся пустой
-- и ни с чем не связана: ни внешнего ключа, ни триггера, ни представления.
--
-- Решение владельца 30.08: корень доверия закрепления — СТРОКА В БАЗЕ, вписывает оператор вручную.
-- Подписанное свидетельство из шага 1 убрано: независимый аудит показал, что нарушитель, ради
-- которого оно вводилось, держит служебный ключ, а тем же ключом функция content читает хранилище
-- vaults напрямую — то есть закрепление ему обходить незачем. Колонки под свидетельство заведены
-- сразу и оставлены пустыми, чтобы будущий слой «конверт содержимого» не потребовал второй миграции.
--
-- Автозакрепление по первому предъявлению («кто первый пришёл, тот и закрепил») сознательно НЕ
-- вводится: оно питалось бы от отпечатка, то есть от той самой дыры, которую мы закрываем.

create table if not exists public.device_bindings (
  -- Ключ таблицы — полный отпечаток машины. Честно: это ещё одно место, где он лежит.
  -- Нового доступа это не даёт — в licenses он и так лежит целиком, это его дом.
  fingerprint_hash text primary key
    constraint device_bindings_fp_format check (fingerprint_hash ~ '^[0-9a-f]{64}$'),

  -- Открытый ключ устройства: 32 байта Ed25519 в base64 стандартного алфавита с набивкой.
  -- 32 байта дают ровно 43 знака плюс один знак набивки. Длина СЧИТАЕТСЯ, а не «похожа» —
  -- прямой урок CPD-143, где поле принимало что угодно длиннее шестнадцати знаков.
  device_pubkey text not null
    constraint device_bindings_key_format check (device_pubkey ~ '^[A-Za-z0-9+/]{43}=$'),

  -- Пусто до появления слоя «конверт содержимого». Тип text, категорически не jsonb:
  -- jsonb нормализует порядок ключей и пробелы, а подпись считается по байтам — свидетельство,
  -- положенное в jsonb, перестало бы проверяться, и не сразу, а у того, кто первым запишет
  -- ключи в другом порядке.
  certificate      text,
  cert_signature   text
    constraint device_bindings_sig_format check (cert_signature is null or cert_signature ~ '^[A-Za-z0-9+/]{86}==$'),

  issued_at  timestamptz not null default now(),
  issued_by  text not null default '',
  revoked_at timestamptz,
  note       text
);

comment on table  public.device_bindings is
  'CPD-141 шаг 1: закрепление ключа машины. Строку вписывает оператор. Пусто = закрепления нет.';
comment on column public.device_bindings.certificate is
  'Пусто до слоя «конверт содержимого». Хранить дословно подписанные байты, не jsonb.';
comment on column public.device_bindings.revoked_at is
  'Заполнено = закрепление снято. Читатели обязаны отбирать по is null, а не удалять строку.';

-- Два рубежа, а не один. В остальных таблицах проекта права роли anon выданы полностью, и доступ
-- держится ТОЛЬКО построчной защитой без политик — одна разрешающая политика открыла бы данные.
-- Здесь так не будет: права отзываются, и построчная защита включается сверх этого.
alter table public.device_bindings enable row level security;
revoke all on public.device_bindings from anon, authenticated;

