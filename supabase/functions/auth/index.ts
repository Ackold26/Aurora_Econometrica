// от SHA-256, то есть ровно 64 шестнадцатеричных знака. Оба регистра допускаются намеренно:
// отказывать невиновному из-за прописных букв не за что. Сверка с базой при этом не меняется —
// она как была, регистрозависимая.
const FINGERPRINT_64 = /^[0-9a-fA-F]{64}$/;

// 🔴 ОТПЕЧАТОК УХОДИТ В ЖУРНАЛ ТОЛЬКО УСЕЧЕНИЕМ ДО 12 ЗНАКОВ.
// Полный отпечаток — это пароль: одним его знанием открывается дверь `/content`, и по нему же
// находится лицензия. Он же персональные данные (INV-38). Запись его целиком в `audit_log`
// удваивала число мест, откуда его можно взять: таблица журнала доступна служебному ключу
// целиком, а сам журнал читают и выгружают куда чаще, чем таблицу лицензий.
// Двенадцати знаков хватает с запасом: среди всех боевых лицензий усечения не совпадают ни разу,
// а восстановить по метке отпечаток нельзя.
// 🔴 Имя ключа в журнале НЕ меняется — остаётся прежним `fingerprint_hash`, меняется только
// длина значения. Причина внешняя по отношению к коду: 263 уже накопленных события усечены
// задним числом под этим именем (29.08.2026), и переименование сейчас разложило бы одну и ту же
// величину по двум ключам внутри одной таблицы — разбор отказов пришлось бы вести двумя
// запросами и склейкой. Знать при чтении: в событиях выдачи содержимого та же метка называется
// `fp12` (`content/index.ts`, `shortFingerprint`), поэтому сквозная по обоим журналам выборка
// делается через `coalesce(details->>'fingerprint_hash', details->>'fp12')`.
// 🔴 Оговорка к этой выборке: метка есть ТОЛЬКО у событий отказа входа (`auth_bad_fingerprint`,
// `auth_no_product`, `auth_no_license`) и у событий выдачи содержимого. У `auth_ok`, `auth_signed`,
// `auth_expired`, `auth_bad_cabinets` метки машины нет вовсе — ни до этой правки, ни после. То есть
// «увидеть машину по всему журналу» такой выборкой нельзя, и рассчитывать на это не надо.
// Регистр приводится к нижнему: один и тот же отпечаток, присланный в разном регистре, обязан
// дать ОДНУ метку, иначе выборка по журналу разъедется на две машины вместо одной. Признак того,
// что регистр был не нижний, не теряется — он едет отдельным полем `fp_case` (см. ниже по потоку).
// 🔴 Возвращает `null`, а НЕ пустую строку, для всего, что меткой быть не может.
// Пустая строка неотличима от «метку не посчитали» и молча портит выборку `group by` — без ошибки,
// без единого признака. С `null` ключ либо есть и осмыслен, либо отсутствует целиком; раскрывать
// его надо приёмом `...(метка ? { fingerprint_hash: метка } : {})`, как уже написан `content/index.ts`.
// Это не отвлечённая осторожность: функция зовётся и ДО гейта формата — в событии
// `auth_bad_fingerprint`, где значением бывает `null`, число или список.
// 🔴 Голова проверяется на шестнадцатеричность, а не только на длину — то же правило, что уже
// написано в `shortFingerprint` (`content/index.ts`). До правки расхождение было безобидным:
// функция звалась только ПОСЛЕ гейта, где значение уже доказано. Теперь первый вызов идёт ДО
// гейта, и одной длины мало: значение вроде `Aurora-Econometrica-Node-B-...` уехало бы в журнал
// меткой `aurora-econom` — то есть двенадцатью знаками неизвестного материала в той самой
// таблице, ради разгрузки которой правка и писалась (INV-38). Для события `auth_bad_fingerprint`
// такая метка диагностической ценности не несёт: машину по ней всё равно не опознать, а причину
// разбирают `fp_length` и `fp_type`. Заодно ключ `details->>'fingerprint_hash'` сохраняет единый
// смысл «начало настоящего отпечатка» на всём журнале, включая 263 записи, усечённые задним числом.
function fp12(v: unknown): string | null {
  return typeof v === "string" && /^[0-9a-fA-F]{12}$/.test(v.slice(0, 12))
    ? v.slice(0, 12).toLowerCase()
    : null;
}

