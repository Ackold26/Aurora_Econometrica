/**
 * Верхний регистр ТОЛЬКО у ASCII-букв — дословный перенос `str::to_ascii_uppercase` из Rust.
 *
 * 🔴 Не `String.prototype.toUpperCase()`: тот поднимает регистр по Unicode и на `ß` выдаёт `SS`,
 * то есть меняет ДЛИНУ строки. Сегодня разницы нет (метод всегда из `GET/POST/PUT`), и белый
 * список выше её и не допустит, — но эталонный вектор подаёт сюда `post` строчными, и мы обязаны
 * повторить именно ту реализацию, с которой сверяемся, а не ту, что удобнее.
 */
export function asciiUpperCase(value: string): string {
  let out = "";
  for (let i = 0; i < value.length; i++) {
    const c = value.charCodeAt(i);
    out += c >= 0x61 && c <= 0x7a ? String.fromCharCode(c - 32) : value[i];
  }
  return out;
}

/**
 * Значение заголовка, если оно ровно одно.
 *
 * 🔴 Задвоенный заголовок — единственное место, где мы ЗАВЕДОМО расходимся с узлом Б, и потому
 * поведение здесь названо явно, а не оставлено на усмотрение среды. Узел Б берёт ПОСЛЕДНЕЕ
 * значение (`api.py:600-601`, словарь из пар), а `Headers.get()` в Deno склеивает все значения
 * через `", "` — то есть один и тот же запрос повёл бы себя на двух серверах по-разному.
 * Мы выбираем третье: считать задвоение негодным входом.
 *
 * Почему запятая — надёжный признак, а не догадка: во всех четырёх подписных заголовках запятая
 * невозможна по составу значений. Подпись, ключ и билет — base64 (`A-Za-z0-9+/=`), одноразовое
 * число — `[A-Za-z0-9_-]` (`auth.py:161-163`), метка времени — только цифры. Значит запятая тут
 * означает ровно одно: значений было больше одного.
 */
export function headerSingle(headers: Headers, name: string): string | null {
  const value = headers.get(name);
  if (value === null) return null;
  return value.includes(",") ? null : value;
}

/**
 * Строгий разбор base64 стандартного алфавита С НАБИВКОЙ.
 *
 * 🔴 Строгость обязана быть НАШЕЙ, а не среды. Узел Б декодирует с `validate=True`
 * (`auth.py:166-170`) и отвергает всё вне алфавита `A-Za-z0-9+/=`.
 *
 * 🔴 Мягкость `atob` ИЗМЕРЕНА, а не взята из общего представления, и оказалась не такой, как
 * записано в рабочем листе. Прогон на Node 24 (проверка 8.3): base64url (`-`, `_`) `atob`
 * **отвергает**, а вот подпись **без хвостовой набивки принимает молча** — 86 знаков вместо 88
 * разбираются, и наружу выходят те же 64 байта. Значит опереться на среду нельзя ровно в одном,
 * но решающем случае: потерянная набивка прошла бы у нас и получила бы отказ на узле.
 * Обе среды следуют одному описанию (WHATWG forgiving-base64), поэтому в Deno ожидается то же —
 * но это ожидание, а не измерение: под Deno прогон не делался.
 *
 * Длина проверяется отдельным доводом: ключ устройства обязан быть ровно 32 байта
 * (`auth.py:345-347`), подпись — ровно 64 (`auth.py:350-351`).
 */
const BASE64_STANDARD = /^[A-Za-z0-9+/]+={0,2}$/;

export function decodeStandardBase64(value: string, expectedLength: number): Uint8Array | null {
  // Кратность четырём отсекает потерянную набивку раньше алфавита: 86 знаков подписи вместо 88 и
  // 43 знака ключа вместо 44 не пройдут именно здесь.
  if (value.length === 0 || value.length % 4 !== 0) return null;
  // Класс знаков не содержит `=`, поэтому набивка возможна только хвостом — отдельной проверки
  // «равенство внутри» не нужно.
  if (!BASE64_STANDARD.test(value)) return null;
  let bytes: Uint8Array;
  try {
    const binary = atob(value);
    bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  } catch {
    return null;
  }
  return bytes.length === expectedLength ? bytes : null;
}

/** Шестнадцатеричная запись НИЖНЕГО регистра — как `hex()` в Rust и `hexdigest()` в Python. */
export function toHexLower(bytes: Uint8Array): string {
  let out = "";
  for (let i = 0; i < bytes.length; i++) out += bytes[i].toString(16).padStart(2, "0");
  return out;
}

/**
 * Свёртка тела.
 *
 * 🔴 Считается от СЫРЫХ БАЙТОВ и до всякого `JSON.parse`. Пересборка тела через `JSON.stringify`
 * перед хешированием изменила бы пробелы, порядок ключей и экранирование — и подпись перестала бы
 * сходиться на теле с русским текстом, который клиент шлёт непроэкранированным.
 * 🔴 Пустое тело ХЕШИРУЕТСЯ, а не даёт пустое поле: `sha256(b"")` = `e3b0c442…b855`
 * (`client.rs:1547`, `auth.py:353`). Пустое поле здесь — самая тихая из возможных ошибок.
 */
export async function sha256HexLower(body: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", body);
  return toHexLower(new Uint8Array(digest));
}

