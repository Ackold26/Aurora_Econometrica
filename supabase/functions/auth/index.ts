// ── SEC-1: Ed25519 signing of the "ok" response ──────────────────────────────
// Threat: an unsigned /auth response lets a forged server / MITM / same-machine cache-forge
// return {status:"ok", cabinets:[all]} and unlock the product without a license. The client
// (crypto/auth_sig.rs) verifies this signature with an embedded public key; without the
// private key an attacker cannot reproduce it on the wire OR in session_cache.json.
//
// Private key: 32-byte raw Ed25519 seed, base64 in env AUTH_SIGNING_PRIVATE_KEY (separate key
// from update/content signing — least privilege). Wrapped in PKCS#8 DER for WebCrypto import.
// Deno Edge Runtime supports "Ed25519" in crypto.subtle natively (KMS Ed25519 blocker of the
// Core aurora_verifier does NOT apply to an env key). Payload = AUTHSIG-v1 canonical string;
// byte-identical to the Rust verifier (proven cross-language: JS V8 sort == Rust UTF-8 sort for
// ASCII slugs; Ed25519 is deterministic per RFC 8032).
const ED25519_PKCS8_PREFIX = new Uint8Array([
  0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x04, 0x22, 0x04, 0x20,
]);

function b64ToBytes(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
function bytesToB64(bytes: Uint8Array): string {
  let bin = "";
  for (let i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
  return btoa(bin);
}

let authSignKeyPromise: Promise<CryptoKey> | null = null;
function getAuthSignKey(): Promise<CryptoKey> {
  if (!authSignKeyPromise) {
    const seedB64 = Deno.env.get("AUTH_SIGNING_PRIVATE_KEY");
    if (!seedB64) return Promise.reject(new Error("AUTH_SIGNING_PRIVATE_KEY not set"));
    const seed = b64ToBytes(seedB64);
    if (seed.length !== 32) {
      return Promise.reject(new Error(`AUTH_SIGNING_PRIVATE_KEY must be 32 bytes, got ${seed.length}`));
    }
    const pkcs8 = new Uint8Array(ED25519_PKCS8_PREFIX.length + 32);
    pkcs8.set(ED25519_PKCS8_PREFIX, 0);
    pkcs8.set(seed, ED25519_PKCS8_PREFIX.length);
    authSignKeyPromise = crypto.subtle.importKey("pkcs8", pkcs8, { name: "Ed25519" }, false, ["sign"]);
  }
  return authSignKeyPromise;
}

async function signAuthResponse(payload: string): Promise<string> {
  const key = await getAuthSignKey();
  const sig = await crypto.subtle.sign({ name: "Ed25519" }, key, new TextEncoder().encode(payload));
  return bytesToB64(new Uint8Array(sig));
}

