/**
 * Верхний регистр ТОЛЬКО у ASCII-букв — дословный перенос `str::to_ascii_uppercase` из Rust.
 *
 * 🔴 Не `String.prototype.toUpperCase()`: тот поднимает регистр по Unicode и на `ß` выдаёт `SS`,
 * то есть меняет ДЛИНУ строки. Сегодня разницы нет (метод всегда из `GET/POST/PUT`), и белый
 * список выше её и не допустит, — но эталонный вектор подаёт сюда `post` строчными, и мы обязаны
 * повторить именно ту реализацию, с которой сверяемся, а не ту, что удобнее.
 */
export function asciiUpperCase(value: string): string {
  let out = "";
  for (let i = 0; i < value.length; i++) {
    const c = value.charCodeAt(i);
    out += c >= 0x61 && c <= 0x7a ? String.fromCharCode(c - 32) : value[i];
  }
  return out;
}

/**
 * Значение заголовка, если оно ровно одно.
 *
 * 🔴 Задвоенный заголовок — единственное место, где мы ЗАВЕДОМО расходимся с узлом Б, и потому
 * поведение здесь названо явно, а не оставлено на усмотрение среды. Узел Б берёт ПОСЛЕДНЕЕ
 * значение (`api.py:600-601`, словарь из пар), а `Headers.get()` в Deno склеивает все значения
 * через `", "` — то есть один и тот же запрос повёл бы себя на двух серверах по-разному.
 * Мы выбираем третье: считать задвоение негодным входом.
 *
 * Почему запятая — надёжный признак, а не догадка: во всех четырёх подписных заголовках запятая
 * невозможна по составу значений. Подпись, ключ и билет — base64 (`A-Za-z0-9+/=`), одноразовое
 * число — `[A-Za-z0-9_-]` (`auth.py:161-163`), метка времени — только цифры. Значит запятая тут
 * означает ровно одно: значений было больше одного.
 */
export function headerSingle(headers: Headers, name: string): string | null {
  const value = headers.get(name);
  if (value === null) return null;
  return value.includes(",") ? null : value;
}

/**
 * Строгий разбор base64 стандартного алфавита С НАБИВКОЙ.
 *
 * 🔴 Строгость обязана быть НАШЕЙ, а не среды. Узел Б декодирует с `validate=True`
 * (`auth.py:166-170`) и отвергает всё вне алфавита `A-Za-z0-9+/=`.
 *
 * 🔴 Мягкость `atob` ИЗМЕРЕНА, а не взята из общего представления, и оказалась не такой, как
 * записано в рабочем листе. Прогон на Node 24 (проверка 8.3): base64url (`-`, `_`) `atob`
 * **отвергает**, а вот подпись **без хвостовой набивки принимает молча** — 86 знаков вместо 88
 * разбираются, и наружу выходят те же 64 байта. Значит опереться на среду нельзя ровно в одном,
 * но решающем случае: потерянная набивка прошла бы у нас и получила бы отказ на узле.
 * Обе среды следуют одному описанию (WHATWG forgiving-base64), поэтому в Deno ожидается то же —
 * но это ожидание, а не измерение: под Deno прогон не делался.
 *
 * Длина проверяется отдельным доводом: ключ устройства обязан быть ровно 32 байта
 * (`auth.py:345-347`), подпись — ровно 64 (`auth.py:350-351`).
 */
const BASE64_STANDARD = /^[A-Za-z0-9+/]+={0,2}$/;

export function decodeStandardBase64(value: string, expectedLength: number): Uint8Array | null {
  // Кратность четырём отсекает потерянную набивку раньше алфавита: 86 знаков подписи вместо 88 и
  // 43 знака ключа вместо 44 не пройдут именно здесь.
  if (value.length === 0 || value.length % 4 !== 0) return null;
  // Класс знаков не содержит `=`, поэтому набивка возможна только хвостом — отдельной проверки
  // «равенство внутри» не нужно.
  if (!BASE64_STANDARD.test(value)) return null;
  let bytes: Uint8Array;
  try {
    const binary = atob(value);
    bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  } catch {
    return null;
  }
  return bytes.length === expectedLength ? bytes : null;
}

/** Шестнадцатеричная запись НИЖНЕГО регистра — как `hex()` в Rust и `hexdigest()` в Python. */
export function toHexLower(bytes: Uint8Array): string {
  let out = "";
  for (let i = 0; i < bytes.length; i++) out += bytes[i].toString(16).padStart(2, "0");
  return out;
}

/**
 * Свёртка тела.
 *
 * 🔴 Считается от СЫРЫХ БАЙТОВ и до всякого `JSON.parse`. Пересборка тела через `JSON.stringify`
 * перед хешированием изменила бы пробелы, порядок ключей и экранирование — и подпись перестала бы
 * сходиться на теле с русским текстом, который клиент шлёт непроэкранированным.
 * 🔴 Пустое тело ХЕШИРУЕТСЯ, а не даёт пустое поле: `sha256(b"")` = `e3b0c442…b855`
 * (`client.rs:1547`, `auth.py:353`). Пустое поле здесь — самая тихая из возможных ошибок.
 */
export async function sha256HexLower(body: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", body);
  return toHexLower(new Uint8Array(digest));
}

/**
 * Путь для подписи — сырой, ровно как пришёл.
 *
 * 🔴 `new URL()`, `decodeURIComponent()`, `normalize()` — ЗАПРЕЩЕНЫ. Они нормализуют процентные
 * последовательности и Unicode, а подпись считается по адресу дословно.
 * Поэтому вырезаем строковой операцией: всё, что после схемы и хоста.
 *
 * 🔴 ЗАМЕРЕНО БОЕМ 30.08 (временный зонд, выложен и удалён): приставка `/functions/v1` СРЕЗАЕТСЯ
 * посредником ДО функции. Обращение по `https://<проект>.supabase.co/functions/v1/probe?a=1`
 * видно внутри как `http://<проект>.supabase.co/probe?a=1`. Значит поле №3 у нас — `/content?…`,
 * а НЕ `/functions/v1/content?…`. Это прямо противоположно устройству шлюза, где приставка
 * `/cloud` в подпись входит: перенести оттуда правило «подписываем адрес целиком» дословно —
 * значит сломать подпись у всех сразу. Отсюда же требование к клиенту: подписывать тот путь,
 * который увидит сервер, а не тот, по которому он постучался.
 *
 * 🔴 Побочно из того же замера: схема внутри — `http://`, хотя клиент шёл по `https://`. В подпись
 * схема не входит вовсе, и вырезание устроено так, что попасть в путь она не может ни при каком
 * раскладе: берём первую косую черту ПОСЛЕ `://`.
 *
 * Возвращает `null`, если разобрать нечего — тогда вызывающий отвечает `bad_request_target`,
 * а не подписывает пустоту.
 */
/**
 * Приставка, которую посредник срезает. Здесь она нужна ТОЛЬКО для разбора причины отказа
 * (см. `вариантыПути`), в подписываемую строку не подставляется никогда.
 */
export const СРЕЗАЕМАЯ_ПРИСТАВКА = "/functions/v1";

/** Процентные тройки строчными — форма, которую посредник до нас приводит к верхней. */
export function percentTriplesToLower(path: string): string {
  return path.replace(/%[0-9A-Fa-f]{2}/g, (m) => m.toLowerCase());
}

/**
 * Известные искажения пути — для РАЗБОРА ПРИЧИНЫ отказа, не для доступа.
 * Возвращает пары «код причины → путь, который мог подписать клиент».
 */
export function вариантыПути(path: string): Array<[string, string]> {
  const варианты: Array<[string, string]> = [];
  const сПриставкой = path.startsWith(СРЕЗАЕМАЯ_ПРИСТАВКА) ? null : СРЕЗАЕМАЯ_ПРИСТАВКА + path;
  const строчные = percentTriplesToLower(path);
  if (сПриставкой) варианты.push(["client_signed_with_prefix", сПриставкой]);
  if (строчные !== path) варианты.push(["client_encoded_percent_lowercase", строчные]);
  if (сПриставкой && строчные !== path) {
    варианты.push(["client_signed_with_prefix_and_lowercase", СРЕЗАЕМАЯ_ПРИСТАВКА + строчные]);
  }
  return варианты;
}

export function extractSignedPath(rawUrl: string): string | null {
  const schemeEnd = rawUrl.indexOf("://");
  if (schemeEnd < 0) {
    // Некоторые среды дают уже относительную цель запроса. Она годится как есть.
    return rawUrl.startsWith("/") ? rawUrl : null;
  }
  const pathStart = rawUrl.indexOf("/", schemeEnd + 3);
  if (pathStart < 0) return null;
  return rawUrl.slice(pathStart);
}

// ── Каноническая строка ─────────────────────────────────────────────────────────────────────

/**
 * Каноническая строка запроса: семь полей через ОДИН перевод строки, завершающего перевода НЕТ.
 *
 * Дословный перенос `build_request_payload` (`protocol.rs:32-50`, `auth.py:128-144`).
 * Ни одно поле не усекается, не приводится к нижнему регистру и не проходит url-кодирование.
 *
 * 🔴 Регистр метода поднимается здесь ПО-ASCII нарочно, чтобы функция оставалась точным переносом
 * и проходила эталонный вектор, который подаёт `post` строчными. Отбор допустимых методов — это
 * отдельное правило и живёт оно в `verifyAuroraRequest`, а не тут: сборщик обязан уметь
 * повторить чужую строку, а не судить о ней.
 */
export function buildRequestPayload(
  method: string,
  path: string,
  timestamp: string,
  nonce: string,
  bodySha256Hex: string,
  fingerprintHash: string,
): string {
  return [
    REQUEST_PREFIX,
    asciiUpperCase(method),
    path,
    timestamp,
    nonce,
    bodySha256Hex,
    fingerprintHash,
  ].join("\n");
}

// ── Подпись ─────────────────────────────────────────────────────────────────────────────────

/**
 * Проверка подписи Ed25519.
 *
 * 🔴 Чистый EdDSA: сообщение передаётся ЦЕЛИКОМ, хеш снаружи не считается — Ed25519 хеширует
 * внутри себя (RFC 8032). Передача хеша вместо сообщения даёт «работающую» проверку, которая не
 * сойдётся ни с одним живым клиентом, и обнаруживается это только сквозным прогоном.
 *
 * 🔴 Любая беда — это «не сошлось», а не исключение. Так устроена проверяющая сторона узла
 * (`auth.py:150-158`), и так же обязана вести себя наша: negodный ключ, негодная подпись,
 * неподдерживаемый алгоритм — всё это `false`, а не падение обработчика в общий перехват с
 * ответом 500 законному клиенту.
 */
export async function verifyEd25519(
  publicKeyRaw32: Uint8Array,
  message: Uint8Array,
  signature64: Uint8Array,
): Promise<boolean> {
  try {
    const key = await crypto.subtle.importKey(
      "raw",
      publicKeyRaw32,
      { name: "Ed25519" },
      false,
      ["verify"],
    );
    return await crypto.subtle.verify(
      { name: "Ed25519" },
      key,
      signature64,
      message,
    );
  } catch {
    return false;
  }
}

// ── Сборка целиком ──────────────────────────────────────────────────────────────────────────

export interface VerifyInput {
  /** `req.method`. */
  method: string;
  /** `req.url` СЫРЫМ, без разбора. */
  rawUrl: string;
  /** `req.headers`. */
  headers: Headers;
  /** Сырые байты тела: `new Uint8Array(await req.arrayBuffer())`. Для GET — пустой массив. */
  bodyBytes: Uint8Array;
  /**
   * Отпечаток машины — поле №7 канонической строки.
   *
   * 🔴 Доводом, а не вычислением внутри. В контуре шлюза он берётся ИЗ БИЛЕТА
   * (`x-aurora-ticket`), а не из тела; в нашем контуре билета в запросе может не быть вовсе —
   * `content` получает отпечаток строкой запроса, `auth` — телом. Это расхождение контуров, и
   * решать его должен вызывающий, зная свой случай, а не чистый модуль.
   */
  fingerprintHash: string;
  /**
   * Открытый ключ устройства в base64 — 🔴 ИЗ ЗАКРЕПЛЕНИЯ, никогда из заголовка `x-aurora-device`.
   * Ключ из заголовка приносит с собой сам предъявитель, и проверка им доказывает лишь то, что
   * запрос согласован сам с собой. Ровно этим был дефект CPD-124.
   */
  devicePublicKeyB64: string;
  /** Наше время в секундах — доводом, чтобы измерение расхождения было проверяемым. */
  nowUnixSeconds?: number;
}

export async function verifyAuroraRequest(input: VerifyInput): Promise<VerifyResult> {
  const now = input.nowUnixSeconds ?? Math.floor(Date.now() / 1000);
  const ответ = (verdict: Verdict, detail: string, skew: number | null = null): VerifyResult => ({
    verdict,
    detail,
    skewSeconds: skew,
  });

  // 1. Подпись есть вообще? Её отсутствие — не ошибка, а обычное сегодняшнее состояние: весь парк
  //    ходит неподписанным. Вызывающий на этом вердикте не делает НИЧЕГО.
  const signatureB64 = headerSingle(input.headers, HEADER.signature);
  if (signatureB64 === null) {
    const задвоена = input.headers.get(HEADER.signature) !== null;
    return ответ("request_unsigned", задвоена ? "signature_header_duplicated" : "no_signature_header");
  }

  // 2. Способ обращения — по белому списку (см. довод у `ALLOWED_METHODS`).
  if (!ALLOWED_METHODS.has(input.method)) {
    return ответ("bad_method", `method_not_allowed:${input.method.length}`);
  }

  // 3. Путь — сырой.
  const path = extractSignedPath(input.rawUrl);
  if (path === null) return ответ("bad_request_target", "url_without_path");

  // 4. Метка времени и одноразовое число. Оба обязаны присутствовать ровно по одному разу: без них
  //    каноническую строку не собрать. 🔴 Их СОДЕРЖИМОЕ при этом не проверяется и поводом для
  //    отказа не служит — решение владельца. Мы только подставляем их как есть.
  const timestamp = headerSingle(input.headers, HEADER.timestamp);
  const nonce = headerSingle(input.headers, HEADER.nonce);
  if (timestamp === null || nonce === null) {
    return ответ(
      "bad_headers",
      `missing_or_duplicated:${timestamp === null ? "timestamp" : ""}${nonce === null ? "nonce" : ""}`,
    );
  }

  // Расхождение часов — только измерение. `/^\d+$/`, а не `Number()`: метка `01785000000`
  // читается как число, но в строку обязана поехать с ведущим нулём, и путать эти два вопроса
  // нельзя. Здесь мы отвечаем на второй, не трогая первый.
  const skew = /^\d+$/.test(timestamp) ? now - Number(timestamp) : null;

  // 5. Ключ устройства из закрепления: ровно 32 байта.
  const deviceKey = decodeStandardBase64(input.devicePublicKeyB64, 32);
  if (deviceKey === null) return ответ("device_key_invalid", "device_key_not_32_bytes", skew);

  // 6. Подпись: ровно 64 байта, строгий стандартный base64.
  //    Код вердикта здесь `request_unsigned` — так же, как на узле (`auth.py:350-351`), где
  //    отсутствие подписи и негодная её длина дают один код. Различие уезжает в подробность.
  const signature = decodeStandardBase64(signatureB64, 64);
  if (signature === null) return ответ("request_unsigned", "signature_malformed_or_not_64_bytes", skew);

  // 7. Свёртка тела и каноническая строка.
  const bodyHash = await sha256HexLower(input.bodyBytes);
  const payload = buildRequestPayload(
    input.method,
    path,
    timestamp,
    nonce,
    bodyHash,
    input.fingerprintHash,
  );

  // 8. Собственно проверка.
  const сообщение = new TextEncoder().encode(payload);
  if (await verifyEd25519(deviceKey, сообщение, signature)) return ответ("ok", "verified", skew);

  // 9. Подпись не сошлась — разбираем ПОЧЕМУ, но вердикт не меняем.
  //
  // 🔴 Довод. Замер боем 30.08 вскрыл две ловушки, каждая из которых ломает подпись у ВСЕХ сразу и
  // при этом невидима: (а) клиент подписал путь вместе с приставкой `/functions/v1`, которую
  // посредник срезает; (б) клиент закодировал процентные тройки строчными, а посредник привёл их
  // к верхнему регистру ещё до нас, и отменить это мы не можем. В обоих случаях единственным
  // следом осталось бы «подпись не сходится» — то есть самое бесполезное из возможных сообщений,
  // одинаковое и для вора, и для своей же ошибки в клиенте.
  //
  // Поэтому на ПУТИ ОТКАЗА (и только на нём) пробуем те же байты с известными искажениями пути.
  // Совпадение не даёт доступа и не меняет вердикта — оно лишь называет причину в журнале.
  // Цена: до трёх лишних проверок Ed25519 там, где запрос и так отвергнут; на успешном пути —
  // ноль. Совпадений быть не должно вовсе: если они пойдут, значит клиент собран неверно.
  for (const [код, вариант] of вариантыПути(path)) {
    const другая = new TextEncoder().encode(
      buildRequestPayload(input.method, вариант, timestamp, nonce, bodyHash, input.fingerprintHash),
    );
    if (await verifyEd25519(deviceKey, другая, signature)) {
      return ответ("request_bad_signature", код, skew);
    }
  }
  return ответ("request_bad_signature", "signature_does_not_match", skew);
}
// ⬆⬆⬆ конец дословной копии `request_signature.ts` ⬆⬆⬆

Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  if (req.method !== "GET") {
    return jsonResponse({ status: "error", message: "Method not allowed" }, 405);
  }

  try {
    const url = new URL(req.url);
    const fingerprint_hash = url.searchParams.get("fingerprint_hash");
    const product = url.searchParams.get("product");
    const version = url.searchParams.get("version");
    const file = url.searchParams.get("file");

    if (!fingerprint_hash || !product || !version || !file) {
      return jsonResponse(
        { status: "error", message: "Missing required params: fingerprint_hash, product, version, file" },
        400
      );
    }

    // Строгая проверка сегментов пути. Лицензия сверяется только по `product`,
    // а путь в хранилище склеивается из `product/version/file` — без этой
    // проверки `version=../<чужой-продукт>/<версия>` отдаёт материалы другого
    // продукта владельцу любой действующей лицензии: слой HTTP нормализует
    // `..` до обращения к хранилищу. Проверено боем 27.07.2026 — обход
    // возвращал 200 и файл целиком.
    const SEGMENT = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;
    const safeSegment = (v: string) => SEGMENT.test(v) && !v.includes("..");
    if (!safeSegment(product) || !safeSegment(version) || !safeSegment(file)) {
      return jsonResponse({ status: "error", message: "Invalid params" }, 400);
    }

    // 🔴 Строгая проверка отпечатка — и тоже ДО обращения к базе. Клиент присылает хеш
    // отпечатка машины: `hex::encode` от SHA-256, ровно 64 шестнадцатеричных знака. Прежде
    // формат не проверялся: `shortFingerprint` ниже смотрит лишь первые 12 знаков и только ради
    // метки в журнале, а САМО значение уходило в отбор лицензии как есть. Путаница «сырьё /
    // отпечаток / хеш» — самая частая ошибка выдачи лицензий, она прямо названа таковой в
    // проектной документации (`CLAUDE.md`, правило 3), и однажды она уже дала боевую РАБОЧУЮ
    // лицензию, в поле хеша которой лежало описание железа на 206 знаков: дверь открывалась
    // значением, которое хешем не является. Дверь эта открывается знанием ОДНОГО отпечатка —
    // тем важнее, чтобы предъявленное было того самого вида, что мы выдаём.
    // Оба регистра допускаются намеренно: отказывать невиновному из-за прописных букв не за что.
    // Сверка с базой при этом прежняя, регистрозависимая.
    // Текст ответа — по-русски и человеческим языком: в отличие от функции входа, здесь он
    // ДОЕЗЖАЕТ до глаз. Клиент подставляет тело ответа в строку «Подробность для поддержки»,
    // то есть английское «Invalid fingerprint_hash» человек прочитал бы дословно.
    const FINGERPRINT_64 = /^[0-9a-fA-F]{64}$/;
    if (!FINGERPRINT_64.test(fingerprint_hash)) {
      return jsonResponse({
        status: "error",
        message: "Отпечаток машины передан в неверном виде. Обратитесь в поддержку.",
      }, 400);
    }

    // 🔴 Отпечаток приводится к нижнему регистру ИМЕННО ЗДЕСЬ, а не в функции входа. Гейт выше
    // намеренно допускает оба регистра (отказывать невиновному из-за прописных букв не за что),
    // но сверка с базой регистрозависима — значит вызывающий с верхним регистром прошёл бы
    // проверку и не нашёл лицензию, получив `403 «Лицензия не найдена»` без единой строки в
    // журнале: оператор разбирал бы это как отзыв или порчу данных. Клиент шлёт `hex::encode`,
    // то есть нижний регистр, поэтому сегодня ветка недостижима — приведение тут на будущее.
    // 🔴 Во ВХОДЕ так делать нельзя: там полный отпечаток входит в подписываемую строку
    // `AUTHSIG-v1`, и нормализация разошлась бы с тем, что собирает клиент при проверке подписи.
    // В выдаче содержимого подписи нет, ломать нечего.
    const отпечаток = fingerprint_hash.toLowerCase();

    const supabase = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!
    );

    // 1. Find license by fingerprint + product
    let query = supabase
      .from("licenses")
      .select("id, product, is_active, expires_at")
      .eq("fingerprint_hash", отпечаток)
      .eq("is_active", true);

    // Filter by product if provided
    query = query.eq("product", product);

    const { data: licenses } = await query;

    // 🔴 Срок разбирается ВРЕМЕНЕМ, и непарсящееся значение считается истёкшим, а не
    // «бессрочным». Прежде здесь стояло `new Date(license.expires_at) < new Date()`:
    // `new Date("2026-13-45")` даёт `Invalid Date`, сравнение с `NaN` всегда ложно — и лицензия
    // с испорченным сроком проходила, отдавая ВСЕ файлы кабинетов бессрочно. Функция входа такую
    // лицензию уже отвергает (`auth/index.ts`, функция `момент` и событие `auth_bad_expiry`), то
    // есть правило существовало, но до этого носителя доведено не было — ровно класс CPD-139/140.
    const момент = (x: any): number => {
      const t = Date.parse(String(x?.expires_at ?? ""));
      return Number.isFinite(t) ? t : -Infinity;
    };
    const сейчас = Date.now();

    // 🔴 Из нескольких действующих строк берётся ЖИВАЯ С САМЫМ ПОЗДНИМ СРОКОМ, а не первая
    // попавшаяся: запрос порядка не задаёт, и база вправе вернуть истёкшую первой. Такие пары в
    // бою есть — зонд 23.08 показал на ОДНОЙ машине то 6 кабинетов, то 13, и срок то 01.11.2026,
    // то 14.04.2030. Прежнее `licenses[0]` давало отказ «Лицензия истекла» при живой лицензии
    // рядом: вход работал, обновление кабинетов вставало, и в журнале не оставалось ни строки.
    // Это то же правило владельца от 23.08, которое уже действует в функции входа.
    const все = licenses ?? [];
    const живые = все.filter((x: any) => момент(x) > сейчас);
    const license = живые.length > 0
      ? [...живые].sort((a: any, b: any) => момент(b) - момент(a))[0]
      : null;

    if (!license) {
      // Различаем два случая: строки нет вовсе и строка есть, но негодна по сроку — иначе
      // оператор не отличит «лицензию не выдали» от «срок вышел либо записан неверно».
      return все.length > 0
        ? jsonResponse({ status: "blocked", message: "Лицензия истекла" }, 403)
        : jsonResponse({ status: "blocked", message: "Лицензия не найдена" }, 403);
    }

    // 2. Download file from Storage
    const storagePath = `${product}/${version}/${file}`;
    const { data: fileData, error: downloadError } = await supabase
      .storage
      .from("vaults")
      .download(storagePath);

    if (downloadError || !fileData) {
      return jsonResponse({ status: "error", message: "Файл не найден" }, 404);
    }

    // 3. Тело целиком в память. Через этот адрес ходят файлы кабинетов —
    // единицы и десятки килобайт, и хранилище всё равно отдаёт объект целиком,
    // так что нарезка куска в памяти ничего не удорожает. Отдавать байты, а не
    // Blob, принципиально: только так в ответе появляется явный Content-Length
    // и исчезает порционная передача, которую посредники у клиентов режут.
    const bytes = new Uint8Array(await fileData.arrayBuffer());
    const size = bytes.byteLength;

    const range = parseRange(req.headers.get("range"), size);
    const invalidRange = range === "invalid";

    // 4. Журнал доставки. Пишем только начальный запрос: при докачке кусками по
    // одному-два килобайта запись на каждый кусок раздула бы журнал в десятки
    // раз и сделала бы его непригодным для разбора отказов — а он нужен именно
    // для этого. Признак `ranged` показывает, что клиент качает по частям.
    if (!invalidRange && (range === null || range.start === 0)) {
      // Вердикт подписи запроса `AURORA-REQ-v1` — ТОЛЬКО НАБЛЮДЕНИЕ (шаг 1 CPD-141).
      // Своего номера в счёте 4а/4б нарочно не получает: он стоит ПЕРЕД ними, потому что к
      // мгновению сборки строки журнала вердикт обязан быть готов, а нумеровать его «4в» перед
      // «4а» значило бы соврать читающему о порядке.
      //
      // 🔴 Ни одной новой ветки отказа. Негодная подпись — это поле в журнале и ничего сверх
      // того: подписанных клиентов сегодня НЕТ ни одного, значит первым же следствием отказа
      // стал бы отказ невиновному, а не пойманный вор. Ни `return`, ни `throw` ниже нет и
      // появиться не должно раньше строгого режима, который включается помашинно и отдельным
      // решением.
      //
      // Место выбрано не случайно. Блок исполняется только на НАЧАЛЬНОМ запросе файла
      // (`range === null || range.start === 0`) — значит на кусках диапазонной докачки нового
      // кода нет вовсе. И блок этот в журнал идёт и без нас — значит вердикт уезжает полем в уже
      // существующую строку `content_downloaded`, а новых строк не появляется ни одной.
      // Честная цена, признаём её прямо: на подписанном начальном куске добавляется один оборот
      // к базе ДО отправки байтов. Отменить выдачу проверка не может — файл к этому мгновению
      // уже прочитан, — но задержать на этот оборот может.
      let вердиктПодписи: string | null = null;
      let подробностьПодписи: string | null = null;

      // 🔴 Цена для НЕподписанного запроса — ровно ноль (правило R11): ни обращения к базе, ни
      // строки журнала, ни изменённого поля. Поэтому условие стоит на голом наличии заголовка,
      // прежде всякой работы. `Headers.get` даёт непустое значение и на задвоенном заголовке —
      // и это намеренно: задвоение обязано дойти до разбора и получить своё имя, а не слиться
      // с «подписи не было».
      if (req.headers.get(HEADER.signature) !== null) {
        try {
          // Полнота набора проверяется ДО обращения к базе, и довод тут не в экономии обращения.
          // Живой клиент заголовков подписи не шлёт вовсе, но посредник, расширение браузера или
          // шлюз могут поставить заголовок с тем же именем у машины, которая никогда ничего не
          // подписывала. На шаге 5 именно по этим вердиктам будут решать, кого закрывать:
          // испорченный замер переносит отказ невиновному из шага 1 в шаг 5. Поэтому подписавшей
          // считается только машина с ПОЛНЫМ набором из четырёх заголовков, а всё прочее —
          // отдельный вердикт `bad_headers`, а не разновидность «подпись негодная».
          // 🔴 Правило дословно то же, что во входе (`auth`, ветка с тем же комментарием): две
          // функции, читающие один протокол, обязаны требовать ОДИН набор. Прежде здесь стояла
          // только проверка наличия подписи — и клиент без `x-aurora-device` доходил до модуля в
          // выдаче содержимого, но получал `bad_headers` во входе. Найдено внешним аудитом блока
          // 31.08 как High: клиент, собранный под одну функцию, на шаге 5 был бы закрыт другой.
          // 🔴 `x-aurora-device` требуется НАЛИЧИЕМ, но его значение не используется никогда:
          // ключ из заголовка приносит с собой сам предъявитель, и проверка им доказывала бы лишь
          // согласованность запроса самому себе — дословно дефект CPD-124. Ключ берётся из
          // закрепления, см. ниже (правило R12).
          const отсутствующие = [HEADER.signature, HEADER.timestamp, HEADER.nonce, HEADER.device]
            .filter((имя) => headerSingle(req.headers, имя) === null);
          if (отсутствующие.length > 0) {
            вердиктПодписи = "bad_headers";
            подробностьПодписи = отсутствующие.join("+");
          } else {
          // Закрепление машины. Пустой ответ и ошибка запроса РАЗВОДЯТСЯ с первого дня
          // (правила R4/R5): `[]` — «закрепления нет», ошибка — «неизвестно». Сегодня оба ведут
          // к одному и тому же бездействию, но на шаге 5 именно по этим вердиктам будут решать,
          // кого закрывать, и унаследованное «ошибка выглядит как отсутствие» превратилось бы
          // там в отказ невиновному. Тот же урок уже оплачен счётчиком всплеска ниже.
          const { data: закрепления, error: ошибкаЗакрепления } = await supabase
            .from("device_bindings")
            .select("fingerprint_hash, device_pubkey, revoked_at")
            .eq("fingerprint_hash", отпечаток)
            .is("revoked_at", null)
            .limit(2);

          const строкиЗакрепления = закрепления ?? [];
          if (ошибкаЗакрепления) {
            вердиктПодписи = "unknown";
          } else if (строкиЗакрепления.length === 0) {
            вердиктПодписи = "no_binding";
          } else if (строкиЗакрепления.length > 1) {
            // Двух живых закреплений на один отпечаток быть не может — отпечаток служит
            // первичным ключом таблицы. Но «взять первое попавшееся» мы всё равно не станем:
            // выбор ключа по неопределённому порядку однажды означал бы проверку подписи не тем
            // ключом, а вердикт при этом выглядел бы обычным.
            вердиктПодписи = "binding_unusable";
          } else {
            const итогПодписи = await verifyAuroraRequest({
              method: req.method,
              // Сырым, без разбора: `new URL()` и `decodeURIComponent` нормализуют процентные
              // тройки, а подпись считается по адресу дословно. Путь модуль вырежет сам —
              // строковой операцией, первой косой чертой после `://`.
              rawUrl: req.url,
              headers: req.headers,
              // Тела нет: сюда доходит только `GET`, всё прочее отвергнуто выше ответом 405.
              // 🔴 Пустое тело при этом ХЕШИРУЕТСЯ, а не даёт пустое поле, — этим занимается
              // модуль; наше дело не подсунуть ему выдуманное тело вместо настоящего.
              bodyBytes: new Uint8Array(0),
              // 🔴 ПРАВИЛО R12, на котором держится вся мера, и нарушить его можно незаметно.
              // Открытый ключ обязан быть взят из закрепления ПО ТОМУ ЖЕ САМОМУ значению
              // отпечатка, которое уходит в поле №7 подписываемой строки: не по продукту, не по
              // лицензии, не по «последнему закреплению». Возьми ключ по любому другому
              // признаку — и проверка станет доказывать согласованность запроса самому себе,
              // то есть ровно то, чем был дефект CPD-124. Здесь оба места читают одну и ту же
              // переменную `отпечаток`, и это исполнение правила, а не удачное совпадение.
              // 🔴 Берётся именно приведённое к нижнему регистру значение (правило R2): им же
              // ищется лицензия выше, им же ищется закрепление здесь. Расхождение регистра
              // между поиском ключа и полем №7 сегодня недостижимо (клиент шлёт `hex::encode`,
              // то есть нижний регистр), но развести эти два значения нельзя ни при каких
              // условиях — на их равенстве и стоит R12.
              fingerprintHash: отпечаток,
              devicePublicKeyB64: строкиЗакрепления[0].device_pubkey,
            });
            вердиктПодписи = итогПодписи.verdict;
            подробностьПодписи = итогПодписи.detail;
          }
          } // конец ветви «набор заголовков полон»
        } catch {
          // 🔴 Перехват свой, и он нужен ВМЕСТЕ с разбором поля `error` выше, а не вместо него:
          // клиент Supabase на сетевом сбое не бросает, а возвращает ошибку объектом — это уже
          // проверено живым зондом, см. счётчик всплеска ниже. Без своего перехвата брошенное
          // исключение ушло бы в общий `catch` на конце обработчика, и законный клиент получил
          // бы 500 вместо файла — тот самый отказ невиновному, которого шаг 1 не создаёт.
          вердиктПодписи = "unknown";
          console.error("content: request signature check unavailable");
        }
      }

      // 4а. Метка машины и счётчик всплеска. Считаем ровно там, где и без того
      // идём в журнал, — на начальном запросе файла: при докачке кусками ни
      // одного лишнего обращения к базе не появляется. Один запрос на файл
      // вместо прежних нуля; тело ответа при этом всё равно едет из хранилища,
      // и оно дороже. Весь блок обёрнут так, чтобы отказ журнала не мешал
      // выдаче: при любой ошибке счётчик просто молчит, а файл уходит клиенту.
      const fp12 = shortFingerprint(отпечаток);
      let recentFiles: number | null = null;
      let burst: number | null = null;

      if (fp12) {
        try {
          const since = new Date(Date.now() - BURST_WINDOW_SECS * 1000).toISOString();
          const { data: recent, error: recentError } = await supabase
            .from("audit_log")
            .select("event, p:details->>product, v:details->>version, f:details->>file")
            .in("event", ["content_downloaded", "content_burst"])
            .eq("details->>fp12", fp12)
            .gte("created_at", since)
            .order("created_at", { ascending: false })
            .limit(BURST_SCAN_LIMIT);

          // Клиент не бросает исключений на сетевом сбое, а возвращает ошибку
          // объектом — проверено живым зондом. Считать по пустому ответу в этом
          // случае нельзя: поле `recent_files` тогда показало бы «забрал один
          // файл» там, где счётчик попросту не отработал. Молчим честно.
          if (!recentError) {
            const verdict = assessBurst(
              (recent ?? []) as unknown as BurstRow[],
              fileKey(product, version, file),
              BURST_DISTINCT_FILES
            );
            recentFiles = verdict.distinct;
            if (verdict.report) burst = verdict.distinct;
          }
        } catch {
          // Журнал недоступен — доставку это не касается.
          console.error("content: burst counter unavailable");
        }
      }

      await supabase.from("audit_log").insert({
        event: "content_downloaded",
        license_id: license.id,
        details: {
          product,
          version,
          file,
          size,
          ranged: range !== null,
          ...(fp12 ? { fp12 } : {}),
          ...(recentFiles !== null ? { recent_files: recentFiles } : {}),
          // Вердикт подписи — только когда подпись была. У неподписанного запроса поля не
          // появляется вовсе: отдельное событие «подписи нет» дало бы по строке журнала на
          // каждое обращение всего парка, то есть ровно то, от чего этот журнал только что
          // чистили.
          ...(вердиктПодписи ? { req_sig: вердиктПодписи, cert: "absent" } : {}),
          // 🔴 Причина — ОТДЕЛЬНЫМ полем, а не свёрнутая в вердикт. Замер боем 30.08 вскрыл две
          // ловушки, каждая ломает подпись у всех клиентов сразу, и в журнале обе выглядели бы
          // одинаково: клиент подписал путь вместе с приставкой `/functions/v1`, которую
          // посредник срезает, либо закодировал процентные тройки строчными, а посредник привёл
          // их к верхнему регистру ещё до нас. Без этого поля осталось бы «подпись не сошлась» —
          // самое бесполезное из возможных сообщений, одинаковое и для вора, и для нашей же
          // ошибки в клиенте. Разбор причины доступа не даёт и вердикта не меняет.
          // 🔴 Полный отпечаток и открытый ключ сюда не попадают никогда (правило R10, INV-38).
          ...(подробностьПодписи ? { req_sig_detail: подробностьПодписи } : {}),
        },
      });

      // 4б. Всплеск — отдельной строкой, чтобы его было видно без разбора всего
      // журнала. Ни отказа, ни задержки: к этому мгновению файл уже прочитан и
      // уходит клиенту тем же ответом, что и без всплеска.
      if (burst !== null) {
        try {
          await supabase.from("audit_log").insert({
            event: "content_burst",
            license_id: license.id,
            details: {
              fp12,
              product,
              distinct_files: burst,
              window_secs: BURST_WINDOW_SECS,
              threshold: BURST_DISTINCT_FILES,
            },
          });
        } catch {
          console.error("content: burst event not written");
        }
      }
    }

    if (invalidRange) {
      return new Response(null, {
        status: 416,
        headers: {
          "Content-Range": `bytes */${size}`,
          "Accept-Ranges": "bytes",
          ...corsHeaders,
        },
      });
    }

    const fileHeaders: Record<string, string> = {
      "Content-Type": "application/octet-stream",
      "Content-Disposition": `attachment; filename="${file}"`,
      "Accept-Ranges": "bytes",
      ...corsHeaders,
    };

    // 5. Кусок файла.
    if (range) {
      // Копия, а не подпредставление: тело ответа не должно зависеть от
      // разделяемого буфера.
      const chunk = bytes.slice(range.start, range.end + 1);
      return new Response(chunk, {
        status: 206,
        headers: {
          ...fileHeaders,
          "Content-Range": `bytes ${range.start}-${range.end}/${size}`,
          "Content-Length": String(chunk.byteLength),
        },
      });
    }

    // 6. Файл целиком.
    return new Response(bytes, {
      status: 200,
      headers: { ...fileHeaders, "Content-Length": String(size) },
    });
  } catch (err) {
    return jsonResponse({ status: "error", message: "Internal server error" }, 500);
  }
});
