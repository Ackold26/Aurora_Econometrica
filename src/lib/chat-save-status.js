/**
 * Признак несохранённого сообщения переписки (CPD-41).
 *
 * 🔴 Зачем вынесено отдельной функцией, а не написано внутри `catch` в ChatPanel.
 * До правки отказ сохранения глотался целиком: `catch { /* non-critical *\/ }`. Комментарий
 * противоречил существу — теряется переписка клиента, и узнать об этом можно было только
 * перезапустив продукт. Хуже того, на предпосылке «клиент видит отказ и повторит отправку»
 * построено проектное решение ядра (батч C, пункт C4): при занятом замке реплика пользователя
 * сознательно отклоняется. Интерфейс эту предпосылку отменял — клиент не видел ничего.
 *
 * Логика вынесена сюда, чтобы её можно было проверить сторожем: внутри разметки Svelte она
 * осталась бы непокрытой, а структурная проверка «есть ли что-то в catch» удовлетворяется
 * любой строкой.
 */

/**
 * Пометить сообщение как несохранённое — по паре (роль, отметка времени).
 *
 * Пара, а не одна отметка: у быстрого ответа и реплики пользователя отметки времени
 * различаются, но совпадение двух значений в пределах одной ленты возможно (два вызова в
 * одну миллисекунду), и пометить чужой пузырь — соврать пользователю о противоположном.
 *
 * @param {import('./store.js').ChatMsg[]} list лента сообщений
 * @param {string} role роль сообщения, сохранение которого не удалось
 * @param {number} ts отметка времени этого сообщения
 * @returns {import('./store.js').ChatMsg[]} новая лента; исходная не изменяется
 */
export function markMessageUnsaved(list, role, ts) {
  if (!Array.isArray(list)) return list;
  return list.map((m) => (m.role === role && m.ts === ts ? { ...m, unsaved: true } : m));
}
