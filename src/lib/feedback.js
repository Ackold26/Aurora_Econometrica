// Открытие формы обратной связи из мест, где человек видит сбой (пайплайн) — экран и текст
// ошибки берутся из места вызова, человека о них не спрашивают. Страница настроек открывает
// форму тем же путём, но без этих двух полей: там взять их неоткуда (см. settings/+page.svelte).
import { invoke } from '@tauri-apps/api/core';

/**
 * Человеческий текст отказа при открытии формы обратной связи. Формулировки живут в
 * `commands/feedback.rs` — они уже написаны для человека и называют адрес почты; здесь
 * снимается только служебный код вида «[FB-001] », который нужен поддержке, а не человеку.
 * @param {unknown} raw сырая строка отказа из программы
 */
export function feedbackErrorText(raw) {
  const без_кода = String(raw).replace(/^\[[A-Z]{2}-?\d{3}\]\s*/, '').trim();
  return без_кода
    || 'Открыть форму обратной связи не удалось. Напишите нам на support@auroraai.pro – ответим так же.';
}

/**
 * Открыть форму обратной связи в браузере, передав шаг мастера и текст последней ошибки.
 * Оба параметра необязательны — Rust принимает их как `Option<String>`.
 * @param {string} [ekran] шаг мастера, на котором был человек
 * @param {string} [oshibka] текст последней ошибки (Rust сам обрежет и вычистит пути)
 * @returns {Promise<string>} открытая ссылка
 */
export async function openFeedbackForm(ekran, oshibka) {
  return invoke('open_feedback_form', { ekran, oshibka });
}
