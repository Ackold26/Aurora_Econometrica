/**
 * Сторож честности «зелёной зоны» в расчёте от цели.
 *
 * ЗАЧЕМ. Экран обещал: «Цель должна быть в зелёной зоне коридора – иначе модель
 * экстраполирует за пределы observed range». Обещание не выполнялось: движок
 * коридор ПРОДАЖ не считает вовсе — `optimize/bounds.py::compute_safe_corridor`
 * возвращает `per_channel` и `aggregate_budget`, а `aggregate_sales` живёт
 * ТОЛЬКО в докстринге с пометкой «placeholder, требует forward pass»; в коде его
 * нет, в `goal_seek.py` тоже. Экран падал на запасной ориентир
 * `текущие продажи ×0,7…×1,5`, который наблюдавшимся диапазоном не является, —
 * и клиент принимал решение по обещанию, которого продукт не выполняет.
 *
 * Настоящий расчёт вынесен в P1 (общий прямой проход с профит-фронтиром).
 * До тех пор текст обязан ВЕТВИТЬСЯ: правда про наблюдения — только когда
 * коридор реально пришёл.
 *
 * Проверяется по исходнику: поведение здесь — это текст, который увидит
 * пользователь, а он собирается в разметке компонента.
 */
import { describe, expect, it } from 'vitest';

// Исходник берём импортом `?raw`, а не через fs: под vitest `import.meta.url`
// приходит не файловой схемой (модули отдаёт dev-сервер), а `process` в этом
// окружении не типизирован. `?raw` решает оба вопроса и не требует @types/node.
import src from '../components/pipeline/OptimizeGoalSeek.svelte?raw';

describe('зелёная зона не выдаёт ориентир за наблюдения', () => {
  it('текст ветвится по признаку настоящего коридора', () => {
    expect(src).toContain('corridorIsObserved');
  });

  it('признак выводится из пришедших границ, а не из константы', () => {
    expect(src).toMatch(/corridorIsObserved\s*=\s*\$derived\([\s\S]{0,200}salesCorridor/);
  });

  it('запасная ветка честно называет зону ориентиром от текущего уровня', () => {
    expect(src).toContain('ориентир от текущего уровня');
  });

  it('ветвящийся текст ПОДСТАВЛЕН в блок предупреждений, а не просто объявлен', () => {
    // Внешний аудит, Medium, 2026-08-02: остальные проверки ищут подстроки в
    // исходнике, поэтому зеленели от одного лишь объявления `const corridorNote`.
    // Регрессия «вернуть в attentionTo безусловный литерал, оставив константу
    // висеть» проходила бы весь сторож. Проверяем саму подстановку.
    expect(src).toMatch(/attentionTo=\{\[\s*corridorNote\s*,/);
  });

  it('обещание про наблюдения не стоит безусловно', () => {
    // Прежняя формулировка утверждала это всегда — независимо от того, пришёл
    // коридор или нет. Возврат к ней красит тест.
    expect(src).not.toContain('иначе модель экстраполирует за пределы observed range');
  });

  it('в клиентском тексте нет англицизма observed range', () => {
    // Правило клиентского текста продукта: русский без англицизмов там, где есть
    // аналог. «observed range» → «наблюдавшийся в данных диапазон».
    const clientText = src
      .split('\n')
      .filter((/** @type {string} */ l) => !l.trim().startsWith('*') && !l.trim().startsWith('//'))
      .join('\n');
    expect(clientText).not.toContain('observed range');
  });
});
