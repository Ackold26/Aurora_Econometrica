/** Максимум терминов в одном контексте (бюджет промпта). */
const MAX_TERMS = 8;

/** Русские стоп-слова, не годящиеся как ключ для матча термина в вопросе. */
const STOP = new Set([
  'возврат', 'расход', 'расходы', 'вложения', 'продажи', 'модель', 'модели',
  'канал', 'канала', 'каналов', 'эффект', 'данные', 'данных', 'уровень',
  'значение', 'процент', 'оценка', 'диапазон', 'единица', 'единицы', 'метрика',
]);

/**
 * Ключевые слова термина для матча по тексту вопроса. Берём: латинские
 * аббревиатуры/слова из term.term (ROAS, ROI, adstock, Hill…) и русское
 * головное слово (часть до скобки/запятой), нормализованное до основы.
 * @param {{ id: string, term: string }} t
 * @returns {string[]}
 */
function termKeywords(t) {
  /** @type {string[]} */
  const keys = [];
  // Латинские последовательности длиной ≥2 (ROAS, ROI, MROI, CPU, MCMC, ESS,
  // NRMSE, MAPE, MMM, GRP, TRP, adstock, hill, ess…).
  const latin = t.term.match(/[A-Za-z][A-Za-z-]{1,}/g) || [];
  for (const w of latin) keys.push(w.toLowerCase());
  // Русское головное слово – до первой скобки или запятой.
  const headRu = (t.term.split(/[(,]/)[0] || '').match(/[А-Яа-яЁё-]{4,}/g) || [];
  for (const w of headRu) {
    const lw = w.toLowerCase();
    if (STOP.has(lw)) continue;
    // Основа: отбросить 1–2 последних символа окончания (грубая нормализация
    // для матча «насыщение/насыщения/насыщен»). Минимум 5 символов основы.
    keys.push(lw.length >= 7 ? lw.slice(0, -2) : lw);
  }
  // ≥3: пропускает значимые латинские аббревиатуры (ROI, CPU, MMM, ESS, SOV,
  // GRP) и русские основы (≥4); отсекает только 2-буквенный шум. Латиница в
  // русском вопросе ложных совпадений не даёт (разные алфавиты).
  return keys.filter((k) => k.length >= 3);
}

/**
 * Найти id терминов, упомянутых в тексте вопроса.
 * @param {string} question
 * @returns {string[]}
 */
export function matchTermsInText(question) {
  const q = (question || '').toLowerCase();
  if (!q) return [];
  /** @type {string[]} */
  const hits = [];
  for (const [id, t] of Object.entries(GLOSSARY)) {
    for (const key of termKeywords(t)) {
      if (q.includes(key)) {
        hits.push(id);
        break;
      }
    }
  }
  return hits;
}

/**
 * Собрать релевантные термины для шага и вопроса (по шагу + по совпадению в
 * вопросе). Приоритет совпадениям из вопроса, затем по-шаговые. Лимит MAX_TERMS.
 * @param {{ step?: number, question?: string }} input
 * @returns {Array<{ id: string, term: string, short: string }>}
 */
export function relevantTerms({ step, question } = {}) {
  const fromQuestion = matchTermsInText(question || '');
  const fromStep = typeof step === 'number' && STEP_TERMS[step] ? STEP_TERMS[step] : [];
  /** @type {string[]} */
  const ordered = [];
  const seen = new Set();
  for (const id of [...fromQuestion, ...fromStep]) {
    if (seen.has(id) || !GLOSSARY[id]) continue;
    seen.add(id);
    ordered.push(id);
    if (ordered.length >= MAX_TERMS) break;
  }
  return ordered.map((id) => {
    const t = GLOSSARY[id];
    return { id: t.id, term: t.term, short: t.short };
  });
}

/**
 * Построить справочный контекст для промпта Авроры: карта программы + блок
 * релевантных терминов (short-определения). Возвращает готовую строку или ''.
 *
 * Внимание (INV-50): возвращаемый текст вызывающий обязан положить также в
 * grounding (grounding.jsonFacts), чтобы числа-нормативы справки считались
 * grounded и рантайм-страж не пометил их как выдуманные.
 *
 * @param {{ step?: number, question?: string, includeOverview?: boolean }} [input]
 * @returns {string}
 */
export function buildHelpContext(input = {}) {
  const { step, question, includeOverview = true } = input;
  const parts = [];
  if (includeOverview) parts.push(PROGRAM_OVERVIEW);
  const terms = relevantTerms({ step, question });
  if (terms.length > 0) {
    parts.push('');
    parts.push('Термины (определения из справки программы):');
    for (const t of terms) parts.push(`- ${t.term}: ${t.short}`);
  }
  return parts.join('\n').trim();
}
