/**
 * Человеческий текст отказа обновления по коду ошибки (CPD-167).
 *
 * Раньше окно обновления показывало человеку сырую строку из глубины программы
 * («Download failed: error sending request for url …»). Она не говорит ни что
 * случилось, ни что с этим делать, и написана не на языке человека. Здесь каждому
 * коду отказа отвечает текст из трёх частей: что случилось, чем это плохо,
 * что делать дальше. Сырая строка не теряется — окно прячет её под раскрытие
 * «Подробности» и пишет в журнал: она нужна поддержке для разбора, но не должна
 * быть первым, что видит человек.
 *
 * Коды производит `src-tauri/src/errors.rs` (функция `coded`) в виде префикса
 * `[UP-003] деталь`. Набор кодов обновления — UP-001..UP-005, одинаковый на всей
 * линейке. Незнакомый код обязан дать внятный запасной текст, а не пустоту:
 * отказ невиновному дороже пропуска виноватого.
 */

/** Адрес поддержки, который называем человеку, когда сам он исправить не может. */
const SUPPORT_EMAIL = 'support@auroraai.pro';

/**
 * Код отказа → что случилось, чем плохо, что делать.
 * @type {Record<string, string>}
 */
const UPDATE_ERROR_TEXTS = {
  'UP-001':
    'Сервер обновлений сейчас недоступен, и запросить новую версию не удалось. '
    + 'Без обновления продолжить работу не получится – проверьте подключение к интернету '
    + 'и нажмите «Повторить» через несколько минут.',
  'UP-002':
    'Файл обновления не удалось скачать целиком – связь прервалась. '
    + 'Пока файла нет, обновление не установится: проверьте подключение к интернету '
    + 'и нажмите «Повторить».',
  'UP-003':
    'Скачанный файл обновления повреждён, устанавливать его нельзя – так программа '
    + 'защищается от порчи и подмены файла по дороге. Нажмите «Повторить», файл будет '
    + 'скачан заново.',
  'UP-004':
    'Установить обновление не удалось: запустить установщик не получилось. '
    + 'Чаще всего мешает нехватка места на диске или защитное средство, которое держит '
    + 'файл – освободите место, закройте лишние программы и нажмите «Повторить».',
  'UP-005':
    'Сведения об обновлении пришли в неожидаемом виде, и номер новой версии разобрать '
    + 'не удалось. Своими силами это не исправить – напишите нам на ' + SUPPORT_EMAIL
    + ', мы поправим на своей стороне.',
};

/**
 * Запасной текст для незнакомого кода и для отказа вовсе без кода.
 * Говорит человеку ровно то, что ему нужно: обновление не встало, что нажать,
 * куда написать, если не помогает.
 */
const UPDATE_ERROR_FALLBACK =
  'Обновление установить не удалось. Без него продолжить работу не получится – '
  + 'нажмите «Повторить», а если ошибка повторяется, напишите нам на ' + SUPPORT_EMAIL
  + ', и мы поможем.';

/**
 * Разобрать отказ обновления: человеческий текст, код для поддержки, сырая строка.
 *
 * @param {unknown} err отказ в том виде, в каком его отдал слой Rust
 * @returns {{ code: string, human: string, raw: string }}
 *   `code` — код вида `UP-003` или пустая строка, если кода в отказе нет;
 *   `human` — текст для человека (всегда непустой);
 *   `raw` — исходная строка отказа для подробностей и журнала.
 */
export function describeUpdateError(err) {
  const raw = err === null || err === undefined ? '' : String(err).trim();
  // Код ищем по всей строке, а не только в начале: отказ может прийти обёрнутым.
  const found = raw.match(/\[([A-Z]{2}-\d{3})\]/);
  const code = found ? found[1] : '';
  const human = (code && UPDATE_ERROR_TEXTS[code]) || UPDATE_ERROR_FALLBACK;
  return { code, human, raw };
}
