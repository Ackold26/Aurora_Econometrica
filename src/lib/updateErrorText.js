/**
 * Человеческий текст отказа обновления по коду ошибки (CPD-167).
 *
 * Раньше окно обновления показывало человеку сырую строку из глубины программы
 * («Download failed: error sending request for url …»). Она не говорит ни что
 * случилось, ни что с этим делать, и написана не на языке человека. Здесь каждому
 * коду отказа отвечает текст из трёх частей: что случилось, чем это плохо,
 * что делать дальше. Сырая строка не теряется — окно прячет её под раскрытие
 * «Подробности» и пишет в журнал: она нужна поддержке для разбора, но не должна
 * быть первым, что видит человек.
 *
 * Коды производит общий крейт `aurora_core::errors` (функция `coded_err`;
 * в продукт он приходит реэкспортом через `src-tauri/src/errors.rs`) в виде
 * префикса `[UP-003] деталь`. Набор кодов обновления — UP-001..UP-005, одинаковый
 * на всей линейке. Незнакомый код обязан дать внятный запасной текст, а не пустоту:
 * отказ невиновному дороже пропуска виноватого.
 *
 * 🔴 Текст по коду — не всегда лучший (внешний аудит s43, находка H-1). Один код
 * покрывает 4–8 разных причин, и для части из них `updater.rs` пишет собственный
 * текст «причина + что делать» именно для этого окна. Такую деталь помечают меткой
 * `[клиенту]` (помощник `user_err` там же), и она побеждает таблицу: иначе человек,
 * отказавший в правах администратора, читает про нехватку места на диске и ходит
 * по кругу, а окно блокирует работу. Догадка «в детали есть кириллица» для этого
 * не годится — среди русских деталей `updater.rs` есть служебные и есть склеенные
 * с английским хвостом; признак обязан быть явным. Стык держит сторож
 * `updateErrorText.guard.test.js`, читающий сам `updater.rs`.
 */

/** Адрес поддержки, который называем человеку, когда сам он исправить не может. */
const SUPPORT_EMAIL = 'support@auroraai.pro';

/**
 * Метка «эта деталь написана для клиента» — её ставит `user_err`/`user_text`
 * в `src-tauri/src/commands/updater.rs`. Договор о формате закреплён с обеих
 * сторон: тестом `user_err_marks_client_facing_detail` в Rust и сторожем здесь.
 */
export const USER_TEXT_MARK = '[клиенту]';

/**
 * Код отказа → что случилось, чем плохо, что делать.
 * Это запасной слой: если `updater.rs` прислал помеченный текст, показываем его.
 * @type {Record<string, string>}
 */
export const UPDATE_ERROR_TEXTS = {
  'UP-001':
    'Сервер обновлений сейчас недоступен, и запросить новую версию не удалось. '
    + 'Без обновления продолжить работу не получится – проверьте подключение к интернету '
    + 'и нажмите «Повторить» через несколько минут.',
  'UP-002':
    'Файл обновления не удалось скачать целиком – связь прервалась. '
    + 'Пока файла нет, обновление не установится: проверьте подключение к интернету '
    + 'и нажмите «Повторить».',
  'UP-003':
    'Скачанный файл обновления повреждён, устанавливать его нельзя – так программа '
    + 'защищается от порчи и подмены файла по дороге. Нажмите «Повторить», файл будет '
    + 'скачан заново.',
  'UP-004':
    'Установить обновление не удалось: запустить установщик не получилось. '
    + 'Чаще всего мешает нехватка места на диске или защитное средство, которое держит '
    + 'файл – освободите место, закройте лишние программы и нажмите «Повторить».',
  'UP-005':
    'Сведения об обновлении пришли в неожидаемом виде, и разобрать их не удалось. '
    + 'Своими силами это не исправить – напишите нам на ' + SUPPORT_EMAIL
    + ', мы поправим на своей стороне.',
};

/**
 * Запасной текст для незнакомого кода и для отказа вовсе без кода.
 * Говорит человеку ровно то, что ему нужно: обновление не встало, что нажать,
 * куда написать, если не помогает.
 *
 * 🔴 Проверка подключения названа здесь первой (внешний аудит s43, находка H-2):
 * отсутствие интернета — самая частая причина, и звучать она обязана даже тогда,
 * когда кода в отказе нет. Иначе клиент без интернета пишет письмо в поддержку
 * вместо того, чтобы включить интернет.
 */
export const UPDATE_ERROR_FALLBACK =
  'Обновление установить не удалось. Без него продолжить работу не получится – '
  + 'проверьте подключение к интернету и нажмите «Повторить», а если ошибка '
  + 'повторяется, напишите нам на ' + SUPPORT_EMAIL + ', и мы поможем.';

/**
 * Достать из строки отказа деталь, написанную для клиента.
 *
 * @param {string} raw строка отказа целиком
 * @returns {string} текст после метки или пустая строка, если метки нет
 */
function clientDetail(raw) {
  const at = raw.indexOf(USER_TEXT_MARK);
  if (at === -1) return '';
  return raw.slice(at + USER_TEXT_MARK.length).trim();
}

/**
 * Разобрать отказ обновления: человеческий текст, код для поддержки, сырая строка.
 *
 * @param {unknown} err отказ в том виде, в каком его отдал слой Rust
 * @returns {{ code: string, human: string, raw: string }}
 *   `code` — код вида `UP-003` или пустая строка, если кода обновления в отказе нет;
 *   `human` — текст для человека (всегда непустой);
 *   `raw` — исходная строка отказа для подробностей и журнала.
 */
export function describeUpdateError(err) {
  const raw = err === null || err === undefined ? '' : String(err).trim();
  // Код ищем по всей строке, а не только в начале: отказ может прийти обёрнутым.
  // Только коды обновления (находка L-1/L-6 аудита s43): прежняя `[A-Z]{2}-\d{3}`
  // ловила и чужие подсистемы — человек видел в подписи раскрытия «Подробности ·
  // LI-005», код лицензирования под заголовком отказа обновления, а поддержка шла
  // по ложному следу.
  const found = raw.match(/\[(UP-\d{3})\]/);
  const code = found ? found[1] : '';
  // Деталь, написанная для клиента, точнее таблицы: таблица знает только код,
  // а код покрывает несколько разных причин (H-1).
  const human = clientDetail(raw) || (code && UPDATE_ERROR_TEXTS[code]) || UPDATE_ERROR_FALLBACK;
  return { code, human, raw };
}
