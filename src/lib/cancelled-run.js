/**
 * Что делать с хвостом ОСТАНОВЛЕННОЙ работы, доехавшим до чата.
 *
 * 🔴 Зачем это вынесено отдельно (находка внешнего аудита 2026-08-03).
 * Признак остановки жил ТОЛЬКО в переменной приёмника и снимался следующим
 * вопросом человека. Облачное ожидание длится до минуты, а «Остановить»
 * отпускает окно немедленно — поэтому обычный порядок событий такой:
 *
 *   1. человек останавливает работу и сразу задаёт следующий вопрос;
 *   2. признак остановки снят, идёт новая работа;
 *   3. приезжает хвост ПЕРВОЙ работы — и приёмнику нечем отличить его от своего.
 *
 * Дальше текст остановленной работы либо приклеивался к чужому ответу, либо
 * затирал его целиком: финальное событие облачного пути несёт признак замены.
 * Теперь принадлежность несёт САМО событие (`cancelled_run`), а решение
 * принимается здесь — по одному правилу и проверяемо.
 *
 * Копия того же правила живёт у Oracle: продукты собираются раздельно, общего
 * слоя интерфейса у них нет. Расхождение ловит гейт паритета в каждом из них.
 */

/**
 * @param {boolean} busy идёт ли сейчас другая работа (человек уже спросил дальше)
 * @param {string|undefined|null} notice приписка, которую человек обязан прочитать
 *   в любом случае: номер оставшейся на узле работы, «остановка не подтверждена»
 * @returns {'apply'|'notice'|'skip'}
 *   `apply` — человек всё ещё смотрит на остановленный ответ, текст применим;
 *   `notice` — идёт другая работа, показать ОДНУ приписку отдельным сообщением;
 *   `skip` — идёт другая работа, а сказать нечего.
 */
export function cancelledTailAction(busy, notice) {
  if (!busy) return 'apply';
  return notice && notice.trim() ? 'notice' : 'skip';
}
