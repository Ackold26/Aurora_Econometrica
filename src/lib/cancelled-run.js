/**
 * Что делать с хвостом ОСТАНОВЛЕННОЙ работы, доехавшим до чата.
 *
 * 🔴 Зачем это вынесено отдельно (находка внешнего аудита 2026-08-03).
 * Признак остановки жил ТОЛЬКО в переменной приёмника и снимался следующим
 * вопросом человека. Облачное ожидание длится до минуты, а «Остановить»
 * отпускает окно немедленно — поэтому обычный порядок событий такой:
 *
 *   1. человек останавливает работу и сразу задаёт следующий вопрос;
 *   2. признак остановки снят, идёт новая работа;
 *   3. приезжает хвост ПЕРВОЙ работы — и приёмнику нечем отличить его от своего.
 *
 * Дальше текст остановленной работы либо приклеивался к чужому ответу, либо
 * затирал его целиком (финальное событие облачного пути несёт признак замены).
 *
 * 🔴 Второй заход аудита (тот же день) показал, что первая починка воспроизводила
 * дефект: решение принималось по `$isLoading`, то есть СНОВА по памяти приёмника —
 * сменили только переменную. Стоило следующему вопросу успеть ответить (короткий
 * ответ, секунды), и хвост первой работы дописывался в конец ЕГО текста.
 *
 * Поэтому теперь решение не зависит от состояния приёмника вообще: **хвост
 * остановленной работы никогда не продолжает ленту**. Её полный текст уже показан
 * потоком, а всё, что обязано дойти до человека, — приписка (номер оставшейся на
 * узле работы, «остановка не подтверждена»).
 *
 * Копия того же правила живёт у Oracle: продукты собираются раздельно, общего слоя
 * интерфейса у них нет. Расхождение ловит гейт паритета в каждом дереве.
 */

/**
 * Показывать ли приписку хвоста остановленной работы.
 *
 * @param {string|undefined|null} notice приписка от сервера
 * @returns {'notice'|'skip'} `notice` — показать отдельным сообщением; `skip` — сказать нечего
 */
export function cancelledTailAction(notice) {
  return notice && notice.trim() ? 'notice' : 'skip';
}

/**
 * Вставить служебное сообщение ПЕРЕД активным пузырём ответа, а не в конец ленты.
 *
 * 🔴 Находка внешнего аудита. Облачный путь шлёт поток НАКОПИТЕЛЬНО: каждое событие
 * несёт весь текст с начала, а приёмник склеивает его с последним сообщением, если
 * оно от ассистента. Служебная строка, приписанная в КОНЕЦ во время живого ответа,
 * рвёт эту склейку: следующий кусок видит чужую роль последней и заводит второй
 * пузырь с полным текстом с начала. Человек видит ответ дважды, и обе копии уходят
 * в историю.
 *
 * @template {{role: string}} T
 * @param {T[]} messages текущая лента
 * @param {T} note служебное сообщение
 * @returns {T[]} лента со вставкой перед активным пузырём
 */
export function insertBeforeActiveBubble(messages, note) {
  const last = messages[messages.length - 1];
  const at = last && last.role === 'assistant' ? messages.length - 1 : messages.length;
  return [...messages.slice(0, at), note, ...messages.slice(at)];
}
