/**
 * Текст предупреждения о непереехавшем вложении — проверяется по РЕЗУЛЬТАТУ.
 *
 * 🔴 Зачем отдельная проверка. Внешний аудит показал у соседнего продукта, что
 * чтение исходника обработчика зеленеет на ЗАПАСНОЙ ветке текста: основную
 * ветку можно заменить на что угодно, и гейт молчит. Здесь предъявляются обе
 * ветки и правила клиентского текста.
 */
import { describe, it, expect } from 'vitest';
import { attachmentsSkippedText } from './cloud-warning-text.js';

describe('предупреждение о непереехавшем вложении', () => {
  it('называет файл, причину и действие', () => {
    const текст = attachmentsSkippedText({
      reason: 'файл «бюджет.csv» слишком велик',
      action: 'Уберите его из «Входящих» или замените файлом поменьше.',
    });
    expect(текст, 'человек обязан узнать, какой файл не уехал').toContain('бюджет.csv');
    expect(текст, 'тост обязан называть «Входящие»').toContain('Входящих');
    expect(текст, 'отказ обязан говорить, что делать').toContain('Что делать');
  });

  it('без причины остаётся понятным', () => {
    const текст = attachmentsSkippedText({});
    expect(текст, 'запасная ветка обязана называть «Входящие»').toContain('Входящих');
    expect(текст.length, 'пустой тост человеку ничего не говорит').toBeGreaterThan(20);
  });

  it('не подставляет мусор вместо отсутствующих полей', () => {
    // Событие может прийти с полями не той формы — тост обязан остаться текстом
    // для человека, а не показать «undefined» или «[object Object]».
    const текст = attachmentsSkippedText({ reason: 42, action: { a: 1 } });
    expect(текст).not.toContain('undefined');
    expect(текст).not.toContain('object');
    expect(текст).toContain('Входящих');
  });

  it('держит правила клиентского текста', () => {
    // Правило «без латиницы» — о нашем тексте, а не об имени файла человека.
    const тексты = [
      attachmentsSkippedText({ reason: 'вложение слишком велико', action: 'Уберите его.' }),
      attachmentsSkippedText({}),
    ];
    for (const текст of тексты) {
      expect(текст, `длинное тире: ${текст}`).not.toContain('—');
      expect(текст, `латиница: ${текст}`).not.toMatch(/[A-Za-z]/);
    }
  });
});
