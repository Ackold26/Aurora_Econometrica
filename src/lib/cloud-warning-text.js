/**
 * Тексты предупреждений облачной поставки — отдельно от обработчиков событий.
 *
 * 🔴 Зачем отдельно. Пока текст собирался прямо внутри `listen(...)`, проверить
 * его можно было только чтением исходника обработчика — то есть соседством слов,
 * а не тем, что увидит человек. У Oracle такая проверка зеленела на ЗАПАСНОЙ
 * ветке текста: основную можно было заменить на что угодно, и гейт молчал.
 * Вынесенная функция предъявляется прямо, обеими ветками.
 *
 * Правила клиентского текста те же, что в Core: причина и действие, короткое
 * тире «–», без латиницы и внутренних имён (имя файла приходит от человека и
 * под это правило не подпадает).
 */

/**
 * Что показать, когда файл «Входящих» не уехал в работу.
 *
 * @param {{reason?: unknown, action?: unknown}} data содержимое события
 * @returns {string} текст для человека
 */
export function attachmentsSkippedText(data) {
  const reason = typeof data?.reason === 'string' ? data.reason.trim() : '';
  const action = typeof data?.action === 'string' ? data.action.trim() : '';
  // Причина приходит от продукта: он один знает, ПОЧЕМУ файл не уехал (велик,
  // не прочитался) и как он называется — имя стоит внутри причины.
  const head = reason
    ? `В работу не уехало: ${reason}. Проверьте «Входящие».`
    : 'Один из файлов «Входящих» в работу не уехал.';
  return action ? `${head} Что делать: ${action}` : head;
}
